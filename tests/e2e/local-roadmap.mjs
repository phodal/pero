// Local ROADMAP and ACP execution remain available while Cloud is unresponsive.
import { expect } from '@playwright/test';
import { electron, focusPage } from './electron.mjs';
import { createServer } from 'node:http';
import { mkdir, mkdtemp, readFile, writeFile, realpath, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { resolve } from 'node:path';
import { setAppearance } from './sidebar-controls.mjs';

const root=resolve(import.meta.dirname,'../..');
const temp=await realpath(await mkdtemp(resolve(tmpdir(),'pero-local-roadmap-')));
const out=resolve(root,'test-results/local-roadmap');
await mkdir(out,{recursive:true});
const workspace=resolve(temp,'local-project');
await mkdir(workspace);
const roadmap='# Roadmap\n\n## Offline work\n\n- [ ] contribution-fixture. Create a local result. Acceptance: the file exists.\n  - [ ] Child item\n- [x] Completed source\n\n```md\n- [ ] Example only\n```\n';
await writeFile(resolve(workspace,'ROADMAP.md'),roadmap);
const agents=resolve(temp,'agents.json');
// Every selectable Agent is a fixture, including built-in IDs; test input cannot invoke a real provider.
await writeFile(agents,JSON.stringify([['codex','Codex'],['claude','Claude'],['copilot','GitHub Copilot'],['grok','Grok · OpenCode'],['fixture','Local ACP fixture']].map(([id,name])=>({id,name,command:process.execPath,args:[resolve(root,'tests/fixtures/acp-agent.mjs')]}))));
const settings=resolve(temp,'settings.json');
await writeFile(settings,JSON.stringify({locale:'zh-CN',workbench:{appearance:'light',projects:[]}}));
const requests=[];const pending=[];
let release=false;
const server=createServer((req,res)=>{
  requests.push({method:req.method,url:req.url});
  const reply=()=>{res.writeHead(503,{'Content-Type':'application/json'});res.end(JSON.stringify({error:'Cloud unavailable fixture'}));};
  if(release)reply();else pending.push(reply);
});
await new Promise(done=>server.listen(0,'127.0.0.1',done));
let app,page;const errors=[];
const state=()=>page.evaluate(()=>JSON.parse(window.peroDiagnostics.snapshot()));
const frame=()=>page.evaluate(()=>new Promise(done=>requestAnimationFrame(()=>requestAnimationFrame(done))));
const capture=async name=>{await frame();await page.screenshot({path:resolve(out,name+'.png')});};
try{
  const env={...process.env,PERO_DESKTOP_DATA_DIR:resolve(temp,'profile'),PERO_SETTINGS_PATH:settings,PERO_HISTORY_PATH:resolve(temp,'history.jsonl'),PERO_LOCALE:'zh-CN',PERO_AGENTS_FILE:agents,PERO_CLOUD_URL:`http://127.0.0.1:${server.address().port}`,PERO_OPERATOR_TOKEN:'local-roadmap-fixture'};
  delete env.ELECTRON_RUN_AS_NODE;delete env.PERO_CLIENT_TOKEN;
  app=await electron.launch({args:[...(process.platform==='darwin'?['--use-mock-keychain']:[]),resolve(root,'desktop')],cwd:root,env});
  page=await app.firstWindow();await focusPage(page);page.on('pageerror',error=>errors.push(error.message));
  await page.waitForFunction(()=>window.peroDiagnostics && JSON.parse(window.peroDiagnostics.snapshot()).localRoadmap?.data?.items?.length>100,undefined,{timeout:60000});
  await page.waitForFunction(()=>!document.getElementById('loading'));
  await expect.poll(()=>requests.length).toBeGreaterThan(0);
  expect((await state()).remote.state.loading).toBe(true);
  await frame();await page.mouse.click(100,158);
  await expect.poll(async()=>(await state()).selectedProject).toBe(`workspace:${root}`);
  expect((await state()).localRoadmap.show_cloud).toBe(false);await frame();
  await capture('01-pero-local-cloud-pending');
  // Select another actual workspace through the same Host boundary used by the folder picker.
  await page.evaluate(path=>window.pero.sessionCommand({action:'workspace',path}),workspace);
  await expect.poll(async()=>(await state()).localRoadmap.data.workspace).toBe(workspace);
  expect((await state()).localRoadmap.data.items).toHaveLength(3);
  await frame();await page.mouse.click(100,158);
  await expect.poll(async()=>(await state()).selectedProject).toBe(`workspace:${workspace}`);
  await capture('02-local-list');
  await page.mouse.click(425,213);
  await expect.poll(async()=>(await state()).localRoadmap.show_cloud).toBe(true);await frame();
  await page.mouse.click(325,213);
  await expect.poll(async()=>(await state()).localRoadmap.show_cloud).toBe(false);await frame();
  await page.mouse.click(1415,287);await frame();
  await expect.poll(async()=>(await state()).localRoadmap.show_completed).toBe(true);
  await page.mouse.click(500,466);
  await expect.poll(async()=>(await state()).localRoadmap.selected_line).toBe(7);
  await capture('02-completed-source');
  expect((await state()).chats).toHaveLength(0);
  await page.mouse.click(310,285);await expect.poll(async()=>(await state()).localRoadmap.selected_line).toBe(null);await frame();
  await page.mouse.click(1415,287);await frame();
  await focusPage(page);await page.mouse.click(500,287);await page.keyboard.type('Child');await expect.poll(async()=>(await state()).remote.search).toBe('Child');await capture('02-search');
  await page.mouse.click(500,338);
  await expect.poll(async()=>(await state()).localRoadmap.selected_line).toBe(6);
  await capture('02-filtered-child');
  await page.mouse.click(310,285);await expect.poll(async()=>(await state()).localRoadmap.selected_line).toBe(null);await frame();
  await page.mouse.click(500,287);await page.keyboard.press(process.platform==='darwin'?'Meta+A':'Control+A');await page.keyboard.press('Backspace');await frame();
  await page.mouse.click(500,338);
  await expect.poll(async()=>(await state()).localRoadmap.selected_line).toBe(5);
  await capture('03-local-task');
  // Select the fixture through the visible Agent choice, then execute.
  await page.mouse.click(690,455);await frame();
  await page.mouse.click(790,458);
  await expect.poll(async()=>(await state()).chats.length).toBe(1);
  await expect.poll(async()=>(await state()).chats[0].state).toBe('idle');
  expect((await state()).chats[0].workspace).toBe(workspace);
  expect((await state()).chats[0].agent).toBe('fixture');
  expect((await state()).chats[0].title).toBe('contribution-fixture');
  expect(await readFile(resolve(workspace,'CONTRIBUTOR.md'),'utf8')).toContain('Prepared in the task checkout');
  expect((await state()).chats[0].messages[0].text).toContain('ROADMAP.md:5');
  expect(await readFile(resolve(workspace,'ROADMAP.md'),'utf8')).toBe(roadmap);
  expect(requests.every(req=>req.method==='GET')).toBe(true);
  await capture('04-local-result-cloud-pending');
  release=true;pending.splice(0).forEach(reply=>reply());
  await expect.poll(async()=>(await state()).remote.state.loading).toBe(false);
  expect((await state()).navigation).toBe(0);
  await page.mouse.click(100,158);await frame();
  await page.mouse.click(500,338);await frame();
  await capture('05-open-existing-conversation');
  await page.mouse.click(790,458);await frame();
  expect((await state()).chats).toHaveLength(1);
  await page.mouse.click(100,158);await frame();
  await setAppearance(page,'dark');await capture('06-dark');
  await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].setSize(1000,720));
  await capture('07-narrow-dark');
  // Missing/invalid input and docs fallback recover through the real Host reader.
  await rm(resolve(workspace,'ROADMAP.md'));
  await page.evaluate(()=>window.pero.sessionCommand({action:'load_roadmap'}));
  await expect.poll(async()=>(await state()).localRoadmap.data.error).toBe('not_found');
  await capture('08-missing');
  await mkdir(resolve(workspace,'docs'));await writeFile(resolve(workspace,'docs/ROADMAP.md'),'- [ ] Fallback task\n');
  await page.evaluate(()=>window.pero.sessionCommand({action:'load_roadmap'}));
  await expect.poll(async()=>(await state()).localRoadmap.data.path).toBe('docs/ROADMAP.md');
  await writeFile(resolve(workspace,'docs/ROADMAP.md'),Buffer.from([0xff]));
  await page.evaluate(()=>window.pero.sessionCommand({action:'load_roadmap'}));
  await expect.poll(async()=>(await state()).localRoadmap.data.error).toBe('invalid');
  await capture('09-invalid');
  await writeFile(resolve(workspace,'docs/ROADMAP.md'),'- [ ] Recovered\n');
  await page.evaluate(()=>window.pero.sessionCommand({action:'load_roadmap'}));
  await expect.poll(async()=>(await state()).localRoadmap.data.items[0]?.title).toBe('Recovered');
  expect(errors).toEqual([]);
  await writeFile(resolve(out,'results.json'),JSON.stringify({cloud_requests:requests,local_execution:true,file_effect:true,errors},null,2));
  console.log('Local ROADMAP: Cloud-pending startup, local execution/file effect, no remote mutation, source preservation, workspace switch, recovery, dark/narrow passed.');
}catch(error){if(page){await capture('failure');await writeFile(resolve(out,'failure-state.json'),JSON.stringify(await state(),null,2));}throw error;}
finally{release=true;pending.splice(0).forEach(reply=>reply());if(app)await app.close();server.closeAllConnections();await new Promise(done=>server.close(done));await rm(temp,{recursive:true,force:true});}
