// Real App origin, Host grants, native MCP driver, persisted configuration and OS encryption.
import { expect } from '@playwright/test';
import { electron } from './electron.mjs';
import { clickAppShortcut, setAppearance } from './sidebar-controls.mjs';
import { mkdtemp, mkdir, rm, readFile, readdir } from 'node:fs/promises';
import { resolve } from 'node:path';
import { tmpdir } from 'node:os';
import { fixture } from '../../packages/connectors/test/fixtures/http.mjs';

const root = resolve(import.meta.dirname, '../..'), out = resolve(root, 'test-results/connectors');
await mkdir(out, { recursive: true });
const profile = await mkdtemp(resolve(tmpdir(), 'pero-connectors-e2e-')), remote = await fixture();
const env = { ...process.env, PERO_DESKTOP_DATA_DIR: profile, PERO_LOCALE: 'en', PERO_SETTINGS_PATH: resolve(profile, 'settings.json'), PERO_HISTORY_PATH: resolve(profile, 'history.jsonl') };
delete env.ELECTRON_RUN_AS_NODE; delete env.PERO_APPS_ROOT;
const launch = () => electron.launch({ args: [...(process.platform === 'darwin' ? ['--use-mock-keychain'] : []), resolve(root, 'desktop')], cwd: root, env });
let app;
const errors = [];
try {
  app = await launch();
  let page = await app.firstWindow();
  const open = async () => {
    page.on('pageerror', error => errors.push(error.message));
    await page.waitForFunction(() => window.peroDiagnostics && !document.getElementById('loading'), undefined, { timeout: 60000 });
    await expect.poll(async () => page.evaluate(() => JSON.parse(window.peroDiagnostics.snapshot()).apps?.some(app => app.name === 'connectors')), { timeout: 20000 }).toBe(true);
    await clickAppShortcut(page, 'connectors');
    const frame = page.frameLocator('iframe[title="connectors"]');
    await expect(frame.getByRole('button', { name: /^(Add custom MCP|添加自定义 MCP)$/ })).toBeVisible({ timeout: 20000 });
    return frame;
  };
  let frame = await open();
  await setAppearance(page, 'light');
  await frame.getByLabel('Search', { exact: true }).fill('GitHub');
  await expect(frame.locator('.point-connectors-tile').filter({ hasText: 'GitHub' })).toHaveCount(1);
  await frame.getByLabel('Search', { exact: true }).fill('');
  await page.screenshot({ path: resolve(out, 'catalog-light.png') });
  await frame.getByRole('button', { name: 'Add custom MCP', exact: true }).click();
  const dialog = frame.getByRole('dialog');
  await dialog.locator('textarea').fill(JSON.stringify({ mcpServers: { fixture: { type: 'http', url: remote.origin + '/mcp' } } }));
  await dialog.getByRole('button', { name: 'Import and continue' }).click();
  // Complete the structured definition with an explicit loopback fixture grant.
  await dialog.getByRole('tab', { name: 'JSON', exact: true }).click();
  await dialog.locator('textarea').fill(JSON.stringify({ transport: 'http', url: remote.origin + '/mcp', allowLoopbackHttp: true, tools: ['counter'], headers: { 'X-Resource-Key': { secretRef: 'fixture.key' } } }, null, 2));
  await page.screenshot({ path: resolve(out, 'import-light.png') });
  await dialog.getByRole('button', { name: 'Save configuration', exact: true }).click();
  await expect(dialog.getByText('Configuration saved.', { exact: true })).toBeVisible();
  await dialog.getByRole('button', { name: 'Close', exact: true }).last().click();
  await expect(dialog).toBeHidden();
  const installed = frame.getByRole('button', { name: /Installed connections/ });
  if (await installed.getAttribute('aria-pressed') !== 'true') await installed.click();
  await expect(frame.getByRole('button', { name: 'Details fixture', exact: true })).toBeVisible();
  await frame.getByRole('button', { name: 'Details fixture', exact: true }).click();
  await dialog.getByRole('textbox', { name: 'Secret value', exact: true }).fill('fixture-private-token');
  await dialog.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(dialog.getByRole('textbox', { name: 'Secret value', exact: true })).toBeEmpty();
  await expect(dialog.getByText('Secret saved.', { exact: true })).toBeVisible();
  await dialog.getByRole('button', { name: 'Verify connection', exact: true }).click();
  await expect(dialog.getByText('Verified 1 tools; the probe connection was released.', { exact: true })).toBeVisible();
  await page.screenshot({ path: resolve(out, 'detail-light.png') });
  // Same-origin management route is the production App boundary.
  const request = payload => frame.locator('body').evaluate(async (_element, input) => (await fetch('/host/connectors', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify(input) })).json(), payload);
  const selectedTools = async () => (await request({ operation: 'list' })).result?.find(item => item.connectorId === 'fixture')?.definition.tools;
  const counter = dialog.getByRole('checkbox', { name: /counter/ });
  await counter.uncheck();
  await dialog.getByRole('button', { name: 'Save tool access', exact: true }).click();
  await expect.poll(selectedTools).toEqual([]);
  await counter.check();
  await dialog.getByRole('button', { name: 'Save tool access', exact: true }).click();
  await expect.poll(selectedTools).toEqual(['counter']);
  await dialog.getByRole('button', { name: 'More', exact: true }).click();
  await expect(dialog.getByRole('menuitem').first()).toBeFocused();
  await dialog.getByRole('menuitem').first().press('Escape');
  await expect(dialog.getByRole('menu')).toBeHidden();
  await expect(dialog).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(frame.getByRole('button', { name: 'Details fixture', exact: true })).toBeFocused();
  await setAppearance(page, 'dark');
  await app.evaluate(({ Menu }) => Menu.getApplicationMenu().getMenuItemById('locale-zh-CN').click());
  await expect(frame.getByRole('button', { name: '添加自定义 MCP', exact: true })).toBeVisible();
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1000, 788));
  expect(await frame.locator('html').evaluate(element => element.scrollWidth <= element.clientWidth + 1)).toBe(true);
  await page.screenshot({ path: resolve(out, 'narrow-dark-zh.png') });
  await frame.getByRole('button', { name: /已安装连接/ }).click();
  await expect(frame.locator('.point-connectors-tile').first()).toBeVisible();
  expect(await frame.locator('html').evaluate(element => element.scrollWidth <= element.clientWidth + 1)).toBe(true);
  await page.screenshot({ path: resolve(out, 'catalog-narrow-dark-zh.png') });
  await frame.getByRole('button', { name: /已安装连接/ }).click();
  await frame.getByRole('button', { name: '详情 fixture', exact: true }).click();
  await dialog.getByRole('button', { name: '说明', exact: true }).focus();
  await expect(dialog.getByRole('tooltip').first()).toBeVisible();
  expect(await frame.locator('html').evaluate(element => element.scrollWidth <= element.clientWidth + 1)).toBe(true);
  await page.screenshot({ path: resolve(out, 'detail-narrow-dark-zh.png') });
  await page.keyboard.press('Escape');
  expect(await frame.locator('body').evaluate(() => typeof window.pero)).toBe('undefined');
  const projected = await request({ operation: 'snapshot' });
  expect(JSON.stringify(projected)).not.toContain('fixture-private-token');
  await app.close(); app = undefined;
  const secretFiles = await readdir(resolve(profile, 'connectors/credentials'));
  for (const file of secretFiles) expect((await readFile(resolve(profile, 'connectors/credentials', file))).includes('fixture-private-token')).toBe(false);
  app = await launch(); page = await app.firstWindow();
  frame = await open();
  const list = await request({ operation: 'list' });
  const saved = list.result.find(item => item.connectorId === 'fixture');
  expect(saved.definition.tools).toEqual(['counter']);
  expect((await request({ operation: 'verify', connectorId: 'fixture' })).ok).toBe(true);
  expect((await request({ operation: 'enable', connectorId: 'fixture', enabled: false, expectedRevision: saved.revision })).ok).toBe(true);
  await frame.getByRole('button', { name: /App Use/ }).click();
  await frame.getByRole('dialog').getByRole('button', { name: /^(Try it|试用)$/ }).click();
  await expect.poll(async () => page.evaluate(() => JSON.parse(window.peroDiagnostics.snapshot()).composer)).toMatch(/^\/app-use /);
  await expect.poll(async () => page.evaluate(() => JSON.parse(window.peroDiagnostics.snapshot()).appChatOpen)).toBe(true);
  expect(errors).toEqual([]);
  console.log('Connectors App: import/save, native verification, encrypted secret persistence, restart, disable, en/zh, light/dark, narrow layout and isolated frame passed.');
} finally { await app?.close(); await remote.close(); await rm(profile, { recursive: true, force: true }); }
