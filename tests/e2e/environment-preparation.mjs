// Opt-in: creates real venvs, downloads wheels and binds the actual App backend.
import {expect} from '@playwright/test';
import {electron} from './electron.mjs';
import {clickAppShortcut,setAppearance} from './sidebar-controls.mjs';
import {mkdtemp,mkdir,writeFile,readFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {tmpdir} from 'node:os';
if(process.env.PERO_ENVIRONMENT_PREPARATION_REAL!=='1')throw Error('Set PERO_ENVIRONMENT_PREPARATION_REAL=1 to allow actual dependency installation.');
const root=resolve(import.meta.dirname,'../..'),out=resolve(root,'test-results/environment-preparation');
const profile=await mkdtemp(resolve(tmpdir(),'pero-env-page-'));
await mkdir(out,{recursive:true});
await writeFile(resolve(profile,'settings.json'),JSON.stringify({workbench:{appearance:'light'},app_python:{}}));
const env={...process.env,PERO_DESKTOP_DATA_DIR:profile,PERO_SETTINGS_PATH:resolve(profile,'settings.json'),PERO_HISTORY_PATH:resolve(profile,'history.jsonl'),PERO_BUILTIN_APPS:'environments,control-lab,paper-agent',PERO_LOCALE:'en'};delete env.ELECTRON_RUN_AS_NODE;
let app, page;
try{
 app=await electron.launch({args:['--use-mock-keychain',resolve(root,'desktop')],cwd:root,env});
 page=await app.firstWindow();
 await page.waitForFunction(()=>window.peroDiagnostics && !document.getElementById('loading'),undefined,{timeout:60000});
 await expect.poll(()=>page.evaluate(()=>JSON.parse(window.peroDiagnostics.snapshot()).apps?.some(a=>a.name==='environments'))).toBe(true);
 await clickAppShortcut(page,'environments');
 const frame=page.frameLocator('iframe[title="environments"]');
 await page.screenshot({path:resolve(out,'catalog-empty.png')});
 await frame.getByRole('button',{name:'Create environment',exact:true}).click();
 await frame.getByLabel('Environment name',{exact:true}).fill('Control acceptance');
 await frame.getByRole('radio',{name:'Control',exact:true}).click();
 await page.screenshot({path:resolve(out,'create-light.png')});
 await setAppearance(page,'dark');
 await expect.poll(()=>frame.locator('html').evaluate(el=>el.style.colorScheme)).toBe('dark');
 await app.evaluate(({Menu})=>Menu.getApplicationMenu().getMenuItemById('locale-zh-CN').click());
 await expect(frame.getByLabel('环境名称',{exact:true})).toHaveValue('Control acceptance');
 await page.screenshot({path:resolve(out,'create-dark-zh.png')});
 await app.evaluate(({BrowserWindow})=>{BrowserWindow.getAllWindows()[0].setMinimumSize(480,600);BrowserWindow.getAllWindows()[0].setSize(720,800);});
 expect(await frame.locator('html').evaluate(el=>el.scrollWidth<=el.clientWidth+1)).toBe(true);
 await frame.getByRole('radio',{name:'Control',exact:true}).focus();
 await page.keyboard.press('ArrowRight');
 await expect(frame.getByRole('radio',{name:'Circuit',exact:true})).toBeChecked();
 await page.keyboard.press('ArrowLeft');
 await expect(frame.getByRole('radio',{name:'Control',exact:true})).toBeChecked();
 await expect(frame.getByRole('radio',{name:'Control',exact:true})).toBeFocused();
 await page.screenshot({path:resolve(out,'create-dark-narrow-zh.png')});
 const narrowOrder=await frame.locator('.env-create-form').evaluate(form=>{
  const summary=form.querySelector('.env-create-aside').getBoundingClientRect();
  const footer=form.querySelector('.env-create-footer').getBoundingClientRect();
  return summary.bottom<=footer.top;
 });
 expect(narrowOrder).toBe(true);
 await frame.getByRole('button',{name:'创建并准备',exact:true}).scrollIntoViewIfNeeded();
 await page.screenshot({path:resolve(out,'create-dark-narrow-summary-zh.png')});
 await frame.getByLabel('环境名称',{exact:true}).scrollIntoViewIfNeeded();
 await app.evaluate(({BrowserWindow,Menu})=>{BrowserWindow.getAllWindows()[0].setSize(1280,850);Menu.getApplicationMenu().getMenuItemById('locale-en').click();});
 await setAppearance(page,'light');
 await expect(frame.getByLabel('Environment name',{exact:true})).toHaveValue('Control acceptance');
 await expect.poll(()=>frame.locator('html').evaluate(el=>el.style.colorScheme)).toBe('light');
 const created=page.waitForResponse(response=>response.url().endsWith('/host/environment/profiles') && response.request().postDataJSON()?.operation==='create');
 await frame.getByRole('button',{name:'Create and prepare',exact:true}).click();
 const createdResponse=await created;
 expect(createdResponse.ok(),await createdResponse.text()).toBe(true);
 await expect(frame.getByRole('heading',{name:'Control acceptance',exact:true})).toBeVisible();
 await expect(frame.getByRole('button',{name:'Use this environment',exact:true})).toBeEnabled({timeout:180000});
 await page.screenshot({path:resolve(out,'prepared-light.png')});
 await frame.getByRole('button',{name:'Use this environment',exact:true}).click();
 await frame.getByRole('dialog').getByRole('button',{name:'Cancel',exact:true}).filter({hasText:'Cancel'}).click();
 await expect(frame.getByRole('button',{name:'Bind and restart',exact:true})).toHaveCount(0);
 await frame.getByRole('button',{name:'Use this environment',exact:true}).click();
 await page.screenshot({path:resolve(out,'confirm-light.png')});
 await frame.getByRole('button',{name:'Bind and restart',exact:true}).click();
 await expect(frame.getByText('Currently in use',{exact:true})).toBeVisible({timeout:30000});
 const settings=JSON.parse(await readFile(resolve(profile,'settings.json'),'utf8'));
 expect(settings.app_python.apps['control-lab']).toContain('/environment/profiles/env-');
 await expect(frame.getByRole('button',{name:'Prepare environment',exact:true})).toHaveCount(0);
 await page.screenshot({path:resolve(out,'bound-light.png')});
 await clickAppShortcut(page,'control-lab');
 const control=page.frameLocator('iframe[title="control-lab"]');
 await expect(control.getByRole('heading',{name:'Control Lab',exact:true})).toBeVisible({timeout:30000});
 const calculation=await control.locator('body').evaluate(async()=>{
  const post=async(path,data)=>{const r=await fetch(path,{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(data)});if(!r.ok)throw Error(await r.text());return r.json();};
  const record=await post('/api/experiments',{templateId:'pi-golden',candidateBudget:1});
  await post(`/api/experiments/${record.id}/search`,{});return record.id;
 });
 let result;
 await expect.poll(async()=>{result=await control.locator('body').evaluate(async(_,id)=>(await fetch(`/api/experiments/${id}`)).json(),calculation);return result.status;},{timeout:60000}).not.toBe('running');
 expect(result.trials.length).toBeGreaterThan(0);
 expect(result.trials.every(t=>t.status!=='failed')).toBe(true);
 await writeFile(resolve(out,'calculation.json'),JSON.stringify(result,null,2));
 await clickAppShortcut(page,'environments');
 await app.evaluate(({BrowserWindow})=>{BrowserWindow.getAllWindows()[0].setMinimumSize(480,600);BrowserWindow.getAllWindows()[0].setSize(720,800);});
 await setAppearance(page,'dark');
 await expect.poll(()=>frame.locator('html').evaluate(el=>el.style.colorScheme)).toBe('dark');
 await expect(frame.locator('.env-workspace')).toBeVisible();
 expect(await frame.locator('html').evaluate(el=>el.scrollWidth<=el.clientWidth+1)).toBe(true);
 await page.screenshot({path:resolve(out,'bound-narrow.png')});
 await frame.getByRole('button',{name:'Back',exact:true}).click();
 await page.screenshot({path:resolve(out,'catalog-dark-narrow.png')});
 await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].setSize(1280,850));
 await setAppearance(page,'light');
 await page.screenshot({path:resolve(out,'catalog-light.png')});
 await app.evaluate(({Menu})=>Menu.getApplicationMenu().getMenuItemById('locale-zh-CN').click());
 await expect(frame.getByRole('button',{name:'创建环境',exact:true})).toBeVisible();
 await page.screenshot({path:resolve(out,'catalog-zh.png')});
 await writeFile(resolve(out,'result.json'),JSON.stringify({profile,settings,checks:['real UI create','real wheels installed','bind confirmation cancellation','backend restart','persisted binding','bound environment immutable','narrow overflow']},null,2));
 console.log('PASS',profile);
}catch(error){console.log(await page?.frameLocator('iframe[title="environments"]').locator('body').textContent());await page?.screenshot({path:resolve(out,'failure.png')});throw error;}finally{await app?.close();}
