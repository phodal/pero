// Real Host file I/O and GPUI editor; the OS picker returns an explicit temp file.
import { expect } from '@playwright/test';
import { electron } from './electron.mjs';
import { mkdtemp, mkdir, writeFile, readFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { resolve } from 'node:path';
const root=resolve(process.env.PERO_CONTENT_TEST_ROOT||resolve(import.meta.dirname,'../..'));
const out=resolve(import.meta.dirname,'../../test-results/file-documents');
const temp=await mkdtemp(resolve(tmpdir(),'pero-file-flow-'));
await mkdir(out,{recursive:true});
const path=resolve(temp,'guide.md');
const original='# Document guide\n\nA **rendered** source with 中文.\n\n[Related data](data%20set.json)\n\n'+Array.from({length:100},(_,i)=>`Paragraph ${i}: retained content.\n`).join('\n');
await writeFile(path,original);
await writeFile(resolve(temp,'data set.json'),'[{"n":9007199254740993,"label":"完整数据"}]');
await writeFile(resolve(temp,'agents.json'),'[]');
const app=await electron.launch({args:['--use-mock-keychain',resolve(root,'desktop')],cwd:root,env:{...process.env,PERO_DESKTOP_DATA_DIR:resolve(temp,'desktop'),PERO_LOCALE:'en',PERO_APPS_ROOT:resolve(temp,'apps'),PERO_SETTINGS_PATH:resolve(temp,'settings.json'),PERO_HISTORY_PATH:resolve(temp,'history.jsonl'),PERO_AGENTS_FILE:resolve(temp,'agents.json')}});
let page;
try {
  page=await app.firstWindow();const errors=[];page.on('pageerror',error=>errors.push(error.message));
  const state=()=>page.evaluate(()=>JSON.parse(window.peroDiagnostics.snapshot()));
  const reader=()=>state().then(s=>s.documents[0]?.reader);
  const paint=()=>page.evaluate(()=>new Promise(done=>requestAnimationFrame(()=>requestAnimationFrame(done))));
  const screen=name=>page.screenshot({scale:'css',path:resolve(out,name+'.png')});
  const modifier=process.platform==='darwin'?'Meta':'Control';
  await page.waitForFunction(()=>window.peroDiagnostics && JSON.parse(window.peroDiagnostics.snapshot()).connected && !document.getElementById('loading'),undefined,{timeout:60000});
  await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].setSize(1488,1086));
  await app.evaluate(({dialog})=>{dialog.showMessageBoxSync=()=>1;});
  await app.evaluate(({dialog},file)=>{dialog.showOpenDialog=async()=>({canceled:false,filePaths:[file]});},path);
  await paint();await page.mouse.click(500,300);await page.keyboard.press(`${modifier}+o`);
  await expect.poll(async()=>(await state()).documents.length).toBe(1);
  await expect.poll(async()=>(await reader()).markdown).toBe(true);
  expect((await reader()).source).toBe(false);
  expect((await reader()).bytes).toBe(Buffer.byteLength(original));
  await screen('markdown-preview');
  let b=(await reader()).bounds;
  await page.mouse.click(b.x+45,b.y+124);await paint();
  await expect.poll(async()=>(await state()).documents.length).toBe(2);
  expect((await state()).documents[1].title).toBe('data set.json');
  expect((await state()).documents[1].reader.rows).toBe(1);
  await page.keyboard.press('Control+Shift+Tab');await paint();
  expect((await state()).activeContent.value.source).toContain('guide.md');
  await screen('relative-file-link');
  await page.mouse.click(b.x+100,b.y+16);await paint();
  await expect.poll(async()=>(await reader()).source).toBe(true);
  await page.mouse.click(b.x+240,b.y+100);await page.keyboard.press(`${modifier}+a`);
  const draft='# Edited document\n\n中文 and exact source.\n';
  await page.keyboard.insertText(draft);
  await expect.poll(async()=>(await reader()).dirty).toBe(true);
  await page.keyboard.press(`${modifier}+s`);
  await expect.poll(()=>readFile(path,'utf8')).toBe(draft);
  await expect.poll(async()=>(await reader()).dirty).toBe(false);
  expect((await reader()).revision).toBe(2);
  await screen('saved-file');
  await page.keyboard.press(`${modifier}+a`);await paint();await page.keyboard.insertText('# Unsaved draft\n');
  await expect.poll(async()=>(await reader()).editorBytes).toBe(16);
  await expect.poll(async()=>(await reader()).dirty).toBe(true);
  await writeFile(path,'# External edit\n');await page.keyboard.press(`${modifier}+s`);
  await expect.poll(async()=>(await reader()).fileError).toBe('content.conflict');
  expect(await readFile(path,'utf8')).toBe('# External edit\n');
  await page.keyboard.press(`${modifier}+a`);await paint();await page.keyboard.press(`${modifier}+c`);
  await expect.poll(async()=>(await app.evaluate(({clipboard})=>clipboard.readText()))==='# Unsaved draft\n').toBe(true);
  await screen('conflict-preserves-draft');
  // Reload needs an explicit discard decision, which keeps edits available until confirmed.
  b=(await reader()).bounds;
  await page.mouse.click(b.x+b.width-75,b.y+50);await paint();
  await expect.poll(async()=>(await reader()).confirmClose).toBe(true);
  await screen('confirm-discard');
  await page.mouse.click(b.x+b.width-215,b.y+90);await paint();
  await expect.poll(async()=>(await reader()).dirty).toBe(false);
  await expect.poll(async()=>(await reader()).bytes).toBe(Buffer.byteLength('# External edit\n'));
  expect((await reader()).fileError).toBe(null);
  await screen('reloaded-file');
  b=(await reader()).bounds;await page.mouse.click(b.x+100,b.y+16);await paint();
  await page.mouse.click(b.x+220,b.y+120);await page.keyboard.press(`${modifier}+a`);await paint();await page.keyboard.insertText('discarded draft');
  await expect.poll(async()=>(await reader()).dirty).toBe(true);
  await app.evaluate(({dialog,BrowserWindow})=>{globalThis.__documentPrompts=0;dialog.showMessageBoxSync=()=>{globalThis.__documentPrompts++;return 0;};BrowserWindow.getAllWindows()[0].webContents.reload();});
  await expect.poll(()=>app.evaluate(()=>globalThis.__documentPrompts)).toBe(1);
  expect((await reader()).dirty).toBe(true);
  await page.mouse.click(363,17);await paint();
  await expect.poll(async()=>(await reader()).confirmClose).toBe(true);
  expect((await state()).documents.length).toBe(2);
  await screen('unsaved-close');
  await page.mouse.click(b.x+b.width-210,b.y+50);await paint();
  await expect.poll(async()=>(await state()).documents.length).toBe(1);
  expect(await readFile(path,'utf8')).toBe('# External edit\n');
  await page.keyboard.press(`${modifier}+o`);
  await expect.poll(async()=>(await state()).documents.length).toBe(2);
  expect((await state()).documents[1].reader.bytes).toBe(Buffer.byteLength('# External edit\n'));
  expect(errors).toEqual([]);
  await writeFile(resolve(out,'result.json'),JSON.stringify({checks:['actual picker command -> Host -> Markdown workspace','complete source retained','editable source and actual disk save','external-change conflict preserves draft','explicit discard and reload','relative UTF-8 file link','dirty close requires discard','reload/window discard guard keeps edits by default','reopen reads current disk source'],errors},null,2));
  console.log('Verified Markdown file open, source edit, actual save, conflict preservation and explicit reload.');
} catch(error) {
  if(page){await page.screenshot({scale:'css',path:resolve(out,'failure.png')});await writeFile(resolve(out,'failure.json'),await page.evaluate(()=>window.peroDiagnostics.snapshot()));}
  throw error;
} finally {await app.close();}
