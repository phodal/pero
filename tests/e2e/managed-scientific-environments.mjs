// Explicit live Host/Electron acceptance. Uses a previously prepared disposable PC-Gym profile.
import {expect} from '@playwright/test';
import {electron} from './electron.mjs';
import {clickAppShortcut,setAppearance} from './sidebar-controls.mjs';
import {chooseSelect} from './select-control.mjs';
import {cp,mkdtemp,mkdir,writeFile,readFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {tmpdir} from 'node:os';
if(process.env.PERO_ENVIRONMENT_PREPARATION_REAL!=='1')throw Error('Real preparation opt-in required');
if(!process.env.PERO_UV_LIVE_HOME||!process.env.PERO_HOST_EXECUTABLE)throw Error('Supply prepared PC-Gym home and fixed Host binary');
const root=resolve(import.meta.dirname,'../..'),out=resolve(root,'test-results/issue-163-production-ui');
const profile=await mkdtemp(resolve(tmpdir(),'pero-163-production-ui-'));
await mkdir(out,{recursive:true});
const records=JSON.parse(await readFile(resolve(process.env.PERO_UV_LIVE_HOME,'profiles.json'),'utf8'));
const ready={...records.find(value=>value.label==='first'),label:'Managed PC-Gym',bound:false};
const catalog=resolve(profile,'environment/profiles');await mkdir(catalog,{recursive:true});
await writeFile(resolve(catalog,ready.id+'.json'),JSON.stringify(ready));
await cp(resolve(process.env.PERO_UV_LIVE_HOME,'environment/uv-0.12.20'),resolve(profile,'environment/uv-0.12.20'),{recursive:true});
await writeFile(resolve(profile,'settings.json'),JSON.stringify({workbench:{appearance:'light'}}));
const env={...process.env,PERO_DESKTOP_DATA_DIR:profile,PERO_SETTINGS_PATH:resolve(profile,'settings.json'),PERO_HISTORY_PATH:resolve(profile,'history.jsonl'),PERO_BUILTIN_APPS:'environments,control-lab,paper-agent',PERO_LOCALE:'en',PERO_APP_PYTHON:process.env.PERO_SCIENTIFIC_APP_PYTHON};
delete env.ELECTRON_RUN_AS_NODE;delete env.PERO_APPS_ROOT;
let app,page,frame;const shot=name=>page.screenshot({path:resolve(out,name+'.png')});
const list=()=>frame.locator('body').evaluate(async()=>{const r=await fetch('/host/environment/profiles',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({operation:'list',compute:true})});if(!r.ok)throw Error(await r.text());return r.json();});
try {
  app=await electron.launch({args:['--use-mock-keychain',resolve(root,'desktop')],cwd:root,env});page=await app.firstWindow();
  await page.waitForFunction(()=>window.peroDiagnostics&&!document.getElementById('loading'),undefined,{timeout:60000});
  await clickAppShortcut(page,'environments');frame=page.frameLocator('iframe[title="environments"]');
  await frame.getByRole('tab',{name:'Compute',exact:true}).click();
  await frame.getByRole('button',{name:'Managed PC-Gym',exact:true}).click();
  await expect(frame.getByText('PC-Gym · Fixed recipe · PyPI',{exact:true})).toBeVisible();
  await frame.getByRole('button',{name:'Use for this method',exact:true}).click();
  await expect(frame.getByText('Currently selected',{exact:true})).toBeVisible({timeout:60000});
  expect((await list()).find(value=>value.id===ready.id).bound).toBe(true);
  await shot('01-pcgym-selected-light');
  await frame.getByRole('button',{name:'Back to compute profiles',exact:true}).click();
  await frame.getByRole('button',{name:'Create compute profile',exact:true}).click();
  await chooseSelect(frame,'Method','paper-agent.pcgym');
  await frame.getByLabel('Environment name',{exact:true}).fill('PC-Gym review copy');
  await frame.getByRole('button',{name:'Create',exact:true}).click();
  await expect(frame.getByRole('heading',{name:'PC-Gym review copy',exact:true})).toBeVisible();
  expect((await list()).find(value=>value.label==='PC-Gym review copy').target).toBe('paper-agent.pcgym');
  await shot('02-pcgym-created');
  await frame.getByRole('button',{name:'Back to compute profiles',exact:true}).click();
  await frame.getByRole('button',{name:'Create compute profile',exact:true}).click();
  await chooseSelect(frame,'Method','control-lab.python-control');
  await frame.getByLabel('Environment name',{exact:true}).fill('Cancel this preparation');
  await frame.getByRole('button',{name:'Create',exact:true}).click();
  await frame.getByRole('button',{name:'Prepare environment',exact:true}).click();
  await expect(frame.getByRole('button',{name:'Cancel preparation',exact:true})).toBeVisible({timeout:15000});
  await frame.getByRole('button',{name:'Cancel preparation',exact:true}).click();
  await expect(frame.getByRole('alert')).toContainText('Preparation cancelled',{timeout:180000});
  const cancelled=(await list()).find(value=>value.label==='Cancel this preparation');
  expect(cancelled.failure.stage).toBe('cancelled');expect(cancelled.prepared).toBeNull();
  expect((await list()).find(value=>value.id===ready.id).bound).toBe(true);
  await shot('03-cancelled-preparation');
  await frame.getByText('Review project declarations',{exact:true}).click();
  await frame.getByLabel('Project directory or GitHub URL pinned to a commit',{exact:true}).fill(resolve(root,'apps/control-lab'));
  await frame.getByRole('button',{name:'Inspect declarations',exact:true}).click();
  await expect(frame.getByRole('heading',{name:'Review required',exact:true})).toBeVisible({timeout:30000});
  await expect(frame.getByRole('region',{name:'Environment proposal for review'})).toContainText('control==0.10.2');
  expect((await list()).length).toBe(3);
  await shot('04-project-proposal-light');
  await frame.getByLabel('Project directory or GitHub URL pinned to a commit',{exact:true}).fill('https://github.com/MaximilianB2/pc-gym/tree/fbfb36bf84b494cd157cff88292e1fd1b864cee5');
  await frame.getByRole('button',{name:'Inspect declarations',exact:true}).click();
  await expect(frame.getByRole('region',{name:'Environment proposal for review'})).toContainText('jax[cpu]',{timeout:90000});
  await setAppearance(page,'dark');
  await app.evaluate(({BrowserWindow})=>{BrowserWindow.getAllWindows()[0].setMinimumSize(480,600);BrowserWindow.getAllWindows()[0].setSize(720,850);});
  expect(await frame.locator('html').evaluate(el=>el.scrollWidth<=el.clientWidth+1)).toBe(true);
  await shot('05-github-proposal-dark-narrow');
  await writeFile(resolve(out,'verification.json'),JSON.stringify({profile,host:env.PERO_HOST_EXECUTABLE,prepared:ready.prepared,checks:['PC-Gym selection','method-specific creation','real prepare cancellation with structured receipt','existing binding retained','local and fixed GitHub declaration proposals without profile creation','dark narrow layout'],notVerified:['Native','signed package','Windows execution']},null,2));
  console.log('ACCEPTED',profile);
} catch(error) {if(page)await shot('failure');throw error;} finally {await app?.close();}
