// Actual GPUI/Electron interactions, with file-controlled ACP readiness.
import { expect } from '@playwright/test';
import { electron } from './electron.mjs';
import { setAppearance } from './sidebar-controls.mjs';
import { mkdir, mkdtemp, readFile, realpath, rm, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { tmpdir } from 'node:os';
const root = resolve(import.meta.dirname, '../..');
const output = resolve(root, 'test-results/agent-preparation');
const temp = await mkdtemp(resolve(tmpdir(), 'pero-agent-preparation-'));
const gate = resolve(temp, 'ready');
const authGate = resolve(temp, 'auth-ready');
const log = resolve(temp, 'wire.jsonl');
const settings = resolve(temp, 'settings.json');
const agents = resolve(temp, 'agents.json');
const workspace = resolve(temp, 'workspace');
await mkdir(output, { recursive: true });
await mkdir(workspace);
await writeFile(resolve(workspace, 'notes.txt'), 'FROZEN_CONTEXT');
await writeFile(log, '');
await writeFile(settings, JSON.stringify({ chat_agent: 'codex', other: 42 }));
await writeFile(agents, JSON.stringify([
  ...['claude', 'grok', 'copilot', 'qoder', 'opencode'].map(id => ({ id, name: id, command: '/no-such-agent' })),
  ...['codex', 'fast', 'auth', 'broken', 'external'].map(id => ({ id, name: id, command: process.execPath,
    args: [resolve(root, 'tests/fixtures/session-preparation.mjs'), id, log, id === 'codex' ? gate : id === 'auth' ? authGate : '', id === 'broken' ? resolve(temp, 'failure') : ''] })),
]));
const env = { ...process.env, PERO_DESKTOP_DATA_DIR: resolve(temp, 'profile'), PERO_SETTINGS_PATH: settings,
  PERO_HISTORY_PATH: resolve(temp, 'sessions.jsonl'), PERO_AGENTS_FILE: agents, PERO_LOCALE: 'en' };
delete env.ELECTRON_RUN_AS_NODE;
let app;
const errors = [];
async function launch() {
  app = await electron.launch({ args: [...(process.platform === 'darwin' ? ['--use-mock-keychain'] : []), resolve(root, 'desktop')], cwd: root, env });
  const page = await app.firstWindow();
  page.on('pageerror', error => errors.push(error.message));
  await page.waitForFunction(() => window.peroDiagnostics && JSON.parse(window.peroDiagnostics.snapshot()).connected, undefined, { timeout: 60000 });
  await page.waitForFunction(() => !document.getElementById('loading'));
  return page;
}
try {
  let page = await launch();
  const state = () => page.evaluate(() => JSON.parse(window.peroDiagnostics.snapshot()));
  const active = async () => { const s = await state(); return s.chats[s.activeChat]; };
  const wire = async () => (await readFile(log, 'utf8')).trim().split('\n').filter(Boolean).map(line => JSON.parse(line));
  const frame = () => page.evaluate(() => new Promise(done => requestAnimationFrame(() => requestAnimationFrame(done))));
  await page.mouse.click(100, 28);
  await expect.poll(async () => (await active())?.state).toBe('connecting');
  await expect.poll(async () => (await wire()).filter(entry => entry.method === 'session/new').length).toBe(1);
  await frame();
  await page.screenshot({ path: resolve(output, 'preparing.png') });
  await page.mouse.click(800, await page.evaluate(() => innerHeight - 75));
  await page.keyboard.type('send while preparing');
  await page.keyboard.press('Enter');
  await expect.poll(async () => (await active()).queued).toBe('send while preparing');
  expect((await wire()).filter(entry => entry.method === 'session/prompt')).toHaveLength(0);
  await writeFile(gate, 'ready');
  await expect.poll(async () => (await active()).messages.filter(message => message.role === 'assistant').length).toBe(1);
  await expect.poll(async () => (await active()).state).toBe('idle');
  expect((await wire()).filter(entry => entry.method === 'session/prompt')).toHaveLength(1);
  await page.mouse.click(100, 28);
  await expect.poll(async () => (await state()).chats.length).toBe(2);
  await expect.poll(async () => (await active()).state).toBe('idle');
  await frame();
  await page.screenshot({ path: resolve(output, 'ready.png') });
  const input = async text => {
    await page.mouse.click(800, await page.evaluate(() => innerHeight - 75));
    await page.keyboard.press(process.platform === 'darwin' ? 'Meta+a' : 'Control+a');
    await page.keyboard.press('Backspace');
    await page.keyboard.type(text);
    await expect.poll(async () => (await state()).composer).toBe(text);
  };
  const select = async name => {
    await frame();
    const current = await active();
    const folderExtra = Math.max(0, (await state()).workspace.split('/').at(-1).length - 4) * 6;
    const offset = (current.models.length ? 280 + Math.max(0, current.models[0][1].length - 13) * 6 : current.state === 'closed' ? 240 : 180) + folderExtra;
    await page.mouse.click(await page.evaluate(() => innerWidth) - offset, await page.evaluate(() => innerHeight - 20));
    await page.screenshot({ path: resolve(output, `agent-menu-${name}.png`) });
    const available = (await state()).agents.filter(agent => agent.available);
    const count = available.length - available.findIndex(agent => agent.id === name);
    for (let i = 0; i < count; i++) await page.keyboard.press('ArrowUp');
    await page.keyboard.press('Enter');
    await expect.poll(async () => (await active()).agent).toBe(name);
  };
  // Readiness alone must not lock the Agent or directory selectors.
  const oldId = (await active()).id;
  await input('preserved draft');
  await app.evaluate(({ dialog }, path) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [path] }); }, workspace);
  await page.evaluate(() => window.pero.chooseWorkspace());
  await expect.poll(async () => (await active()).workspace).toBe(await realpath(workspace));
  await expect.poll(async () => (await active()).state).toBe('idle');
  expect((await active()).id).not.toBe(oldId);
  expect((await state()).composer).toBe('preserved draft');
  await input('@file notes');
  await expect.poll(async () => (await state()).completion.items).toContain('notes.txt');
  await page.keyboard.press('Enter');
  await expect.poll(async () => (await state()).attachments).toEqual(['notes.txt']);
  await page.keyboard.type(' keep this draft');
  let frozenDraft = (await state()).composer;
  await select('fast');
  await expect.poll(async () => (await active()).state).toBe('idle');
  expect((await state()).composer).toBe(frozenDraft);
  expect((await state()).attachments).toEqual(['notes.txt']);
  expect((await active()).models[0][1]).toBe('fast Model A');
  expect((await state()).chats).toHaveLength(2);
  expect((await wire()).filter(entry => entry.method === 'session/prompt')).toHaveLength(1);
  await page.screenshot({ path: resolve(output, 'switch-keeps-draft.png') });
  // A different Agent can replace an in-flight preparation without losing the draft.
  await rm(gate);
  await select('codex');
  await expect.poll(async () => (await active()).state).toBe('connecting');
  await expect.poll(async () => (await wire()).filter(entry => entry.name === 'codex' && entry.method === 'session/new').length).toBe(4);
  const retiredPid = (await wire()).filter(entry => entry.name === 'codex' && entry.method === 'session/new').at(-1).pid;
  await select('fast');
  await expect.poll(async () => (await active()).state).toBe('idle');
  await writeFile(gate, 'ready');
  await expect.poll(() => { try { process.kill(retiredPid, 0); return false; } catch { return true; } }).toBe(true);
  expect((await state()).composer).toBe(frozenDraft);
  expect((await state()).chats).toHaveLength(2);
  // Startup failure has a retry action and keeps the editor's frozen references.
  await select('broken');
  await expect.poll(async () => (await active()).state).toBe('closed');
  expect((await state()).composer).toBe(frozenDraft);
  await frame();
  await page.screenshot({ path: resolve(output, 'startup-error.png') });
  await page.mouse.click(await page.evaluate(() => innerWidth - 105), await page.evaluate(() => innerHeight - 20));
  await expect.poll(async () => (await active()).state).toBe('idle');
  expect((await state()).attachments).toEqual(['notes.txt']);
  await select('auth');
  await expect.poll(async () => (await active()).state).toBe('connecting');
  await page.mouse.click(800, await page.evaluate(() => innerHeight - 75));
  await page.keyboard.press('Enter');
  await expect.poll(async () => (await active()).queued).toBe(frozenDraft);
  await input('follow-up draft');
  frozenDraft += '\nfollow-up draft';
  await writeFile(authGate, 'ready');
  await expect.poll(async () => (await active()).state).toBe('auth_required');
  await expect.poll(async () => (await state()).composer).toBe(frozenDraft);
  expect((await state()).attachments).toEqual(['notes.txt']);
  expect((await wire()).filter(entry => entry.method === 'authenticate')).toHaveLength(0);
  await frame();
  await page.screenshot({ path: resolve(output, 'authentication.png') });
  await page.mouse.click(315, await page.evaluate(() => innerHeight - 178));
  await expect.poll(async () => (await active()).state).toBe('idle');
  expect((await wire()).filter(entry => entry.method === 'session/prompt')).toHaveLength(1);
  expect((await state()).composer).toBe(frozenDraft);
  await select('external');
  await expect.poll(async () => (await active()).state).toBe('auth_required');
  expect((await wire()).filter(entry => entry.method === 'authenticate')).toHaveLength(1);
  await frame();
  await page.screenshot({ path: resolve(output, 'terminal-login.png') });
  await page.mouse.click(360, await page.evaluate(() => innerHeight - 178));
  await expect.poll(async () => (await active()).state).toBe('idle');
  expect((await state()).composer).toBe(frozenDraft);
  expect((await wire()).filter(entry => entry.method === 'session/prompt')).toHaveLength(1);
  await select('fast');
  await expect.poll(async () => (await active()).state).toBe('idle');
  await input('');
  const emptyId = (await active()).id;
  const starts = (await wire()).filter(entry => entry.method === 'initialize').length;
  await page.mouse.click(100, 28);
  await frame();
  expect((await active()).id).toBe(emptyId);
  expect((await wire()).filter(entry => entry.method === 'initialize')).toHaveLength(starts);
  await setAppearance(page, 'dark');
  await frame();
  await page.screenshot({ path: resolve(output, 'dark.png') });
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1000, 788));
  await page.waitForFunction(() => innerWidth === 1000);
  await frame();
  await page.screenshot({ path: resolve(output, 'narrow.png') });
  expect(JSON.parse(await readFile(settings, 'utf8'))).toMatchObject({ chat_agent: 'fast', other: 42 });
  await app.close();
  page = await launch();
  await page.mouse.click(100, 28);
  await expect.poll(async () => (await active())?.state).toBe('idle');
  expect((await active()).agent).toBe('fast');
  expect((await wire()).filter(entry => entry.method === 'session/prompt')).toHaveLength(1);
  await frame();
  await page.screenshot({ path: resolve(output, 'remembered-agent.png') });
  await app.close();
  const unavailable = JSON.parse(await readFile(agents, 'utf8')).map(agent => ({ ...agent, command: '/no-such-agent' }));
  await writeFile(agents, JSON.stringify(unavailable));
  const beforeUnavailable = (await wire()).length;
  page = await launch();
  await page.mouse.click(100, 28);
  await input('keep this until an Agent is installed');
  await page.keyboard.press('Enter');
  expect((await state()).composer).toBe('keep this until an Agent is installed');
  expect((await active()).queued).toBe(null);
  expect((await state()).chats.filter(chat => chat.messages.length === 0)).toHaveLength(1);
  expect((await wire()).length).toBe(beforeUnavailable);
  await frame();
  await page.screenshot({ path: resolve(output, 'no-agent.png') });
  expect(errors).toEqual([]);
  await writeFile(resolve(output, 'result.json'), JSON.stringify({ state: await state(), wire: await wire(), errors, temp }, null, 2));
  console.log(JSON.stringify({ output, temp }));
} catch (error) {
  const page = await app.firstWindow();
  console.error(await page.evaluate(() => window.peroDiagnostics?.snapshot()));
  await page.screenshot({ path: resolve(output, 'failure.png') });
  throw error;
} finally { await app?.close(); }
