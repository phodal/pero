// Explicit opt-in: installs the real Control Lab Python dependencies from PyPI.
import { expect } from '@playwright/test';
import { electron } from './electron.mjs';
import { clickAppOpen, setAppearance, clickAppShortcut } from './sidebar-controls.mjs';
import { mkdtemp, mkdir, writeFile, readFile, rm, access, realpath } from 'node:fs/promises';
import { resolve } from 'node:path';
import { tmpdir } from 'node:os';
if (process.env.PERO_APP_PREPARATION_NETWORK !== '1') throw new Error('Set PERO_APP_PREPARATION_NETWORK=1 to install real Python packages');
const root = resolve(import.meta.dirname, '../..');
const out = resolve(root, 'test-results/app-preparation');
await mkdir(out, { recursive: true });
const profile = await realpath(await mkdtemp(resolve(tmpdir(), 'pero-app-preparation-')));
const environment = resolve(profile, 'environment/pero-python312');
const settings = resolve(profile, 'settings.json');
await writeFile(settings, JSON.stringify({ app_python: { default: environment } }));
const env = { ...process.env, PERO_DESKTOP_DATA_DIR: profile, PERO_SETTINGS_PATH: settings, PERO_BUILTIN_APPS: 'control-lab', PERO_REQUIRED_APPS: '', PERO_LOCALE: 'zh-CN' };
delete env.ELECTRON_RUN_AS_NODE;
delete env.PERO_APP_PYTHON;
delete env.PERO_APPS_ROOT;
let app;
const errors = [], events = [];
const launch = () => electron.launch({ args: [...(process.platform === 'darwin' ? ['--use-mock-keychain'] : []), resolve(root, 'desktop')], cwd: root, env });
try {
  app = await launch();
  let page = await app.firstWindow();
  const observe = async () => {
    page.on('pageerror', error => errors.push(error.message));
    await page.waitForFunction(() => window.peroDiagnostics && !document.getElementById('loading'), undefined, { timeout: 60000 });
    await page.evaluate(() => { window.preparationEvents = []; window.pero.onEvent(event => { if (event.kind === 'apps_preparation') window.preparationEvents.push(event.data); }); });
    await clickAppShortcut(page, 'apps');
  };
  await observe();
  await page.evaluate(() => window.pero.appsCommand({ action: 'apps_enable', name: 'control-lab' }));
  await clickAppOpen(page, 'control-lab');
  let panel = page.locator('.app-panel-status[data-preparation]');
  const background = page.locator('.app-preparation');
  await expect(panel.getByText('环境尚未就绪', { exact: true })).toBeVisible();
  await expect(panel.locator('.app-panel-status-spinner')).toHaveCount(0);
  await expect(page.locator('iframe[title="control-lab"]')).toHaveCount(0);
  await expect(access(environment)).rejects.toMatchObject({ code: 'ENOENT' });
  const originalSettings = await readFile(settings, 'utf8');
  await page.evaluate(() => window.pero.appsCommand({ action: 'apps_project_resources', name: 'control-lab' }));
  await clickAppShortcut(page, 'control-lab');
  await expect.poll(() => page.evaluate(() => window.preparationEvents.length)).toBeGreaterThanOrEqual(3);
  expect(await page.evaluate(() => window.preparationEvents.every(event => event.phase === 'required'))).toBe(true);
  await expect(access(environment)).rejects.toMatchObject({ code: 'ENOENT' });
  expect(await readFile(settings, 'utf8')).toBe(originalSettings);
  await page.screenshot({ path: resolve(out, 'required.png') });
  await setAppearance(page, 'dark');
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1000, 720));
  await expect(panel.getByRole('button', { name: '准备环境', exact: true })).toBeVisible();
  await page.screenshot({ path: resolve(out, 'required-dark-narrow.png') });
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1488, 1054));
  await setAppearance(page, 'light');
  await panel.getByRole('button', { name: '准备环境', exact: true }).click();
  await expect(panel.locator('.app-panel-status-spinner')).toBeVisible({ timeout: 30000 });
  await expect(background).toBeHidden();
  await panel.locator('summary').click();
  await expect(panel.locator('pre')).toBeVisible();
  await page.screenshot({ path: resolve(out, 'installing.png') });
  const frame = page.frameLocator('iframe[title="control-lab"]');
  await expect(frame.getByRole('heading', { name: 'Control Lab', exact: true })).toBeVisible({ timeout: 660000 });
  await expect(panel).toBeHidden();
  await expect(background).toBeHidden();
  events.push(...await page.evaluate(() => window.preparationEvents));
  expect(events.some(event => event.phase === 'creating')).toBe(true);
  expect(events.some(event => event.phase === 'installing')).toBe(true);
  expect(events.some(event => event.phase === 'ready')).toBe(true);
  await expect(frame.locator('main')).toHaveAttribute('aria-busy', 'false', { timeout: 60000 });
  await expect(frame.getByRole('button', { name: 'Generate parameters', exact: true })).toBeEnabled();
  await page.screenshot({ path: resolve(out, 'control-lab.png') });
  await app.close(); app = undefined;
  const configPath = resolve(environment, 'pyvenv.cfg');
  const config = await readFile(configPath, 'utf8');
  await writeFile(configPath, config.replace('include-system-site-packages = false', 'include-system-site-packages = true'));
  app = await launch(); page = await app.firstWindow(); panel = page.locator('.app-panel-status[data-preparation]'); await observe();
  await clickAppOpen(page, 'control-lab');
  await expect(panel.getByText('环境尚未就绪', { exact: true })).toBeVisible();
  await panel.getByRole('button', { name: '准备环境', exact: true }).click();
  await expect(panel.getByRole('alert')).toHaveText('安装失败');
  await expect(page.getByRole('button', { name: '重新安装', exact: true })).toHaveCount(1);
  await expect(page.locator('.app-preparation')).toBeHidden();
  await page.screenshot({ path: resolve(out, 'failed.png') });
  await setAppearance(page, 'dark');
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(640, 680));
  await expect(panel.getByRole('button', { name: '重新安装', exact: true })).toBeVisible();
  await page.screenshot({ path: resolve(out, 'failed-dark-narrow.png') });
  await writeFile(configPath, config);
  await panel.getByRole('button', { name: '重新安装', exact: true }).click();
  await expect(page.frameLocator('iframe[title="control-lab"]').getByRole('heading', { name: 'Control Lab', exact: true })).toBeVisible({ timeout: 30000 });
  await expect(panel).toBeHidden();
  const reused = await page.evaluate(() => window.preparationEvents);
  events.push(...reused);
  expect(reused.some(event => event.phase === 'ready')).toBe(true);
  expect(reused.filter(event => event.phase === 'installing')).toHaveLength(0);
  expect(errors).toEqual([]);
  await writeFile(resolve(out, 'result.json'), JSON.stringify({ passed: true, checks: ['opening and project observation do not acquire an environment', 'explicit preparation action', 'fresh venv creation', 'real Control Lab dependency install', 'progress and logs', 'backend starts after preparation', 'invalid environment fails visibly', 'retry recovers', 'installed environment reused without pip'], events, errors }, null, 2));
  console.log('App preparation: fresh installation, progress, real backend, failure and retry passed.');
} finally {
  if (app) await app.close();
  await rm(profile, { recursive: true, force: true });
}
