"""Fixed stdlib observation plus import readiness for the managed Control recipe.

Also embedded by Host, so prepare and execution compare the exact same observation.
Installed distribution files with RECORD hashes are observed byte-for-byte.
Generated bytecode and prefix-specific CLI launchers are outside this identity.
"""
import hashlib
from importlib import import_module, metadata
import json
import platform
from pathlib import Path
import sys


def observe(method='control'):
    modules = ('numpy', 'scipy.linalg', 'torch', 'gymnasium', 'stable_baselines3', 'casadi',
               'do_mpc', 'jax', 'equinox', 'diffrax') if method == 'pcgym' else ('control', 'numpy', 'scipy.linalg')
    for module in modules:
        import_module(module)
    distributions = sorted(metadata.distributions(), key=lambda d: d.metadata['Name'])
    content = hashlib.sha256()
    for distribution in distributions:
        name = distribution.metadata['Name'].lower().replace('_', '-')
        for entry in sorted(distribution.files or []):
            # RECORD itself and generated pyc have no hash. External launchers
            # embed a prefix and are not used by this fixed module entrypoint.
            if entry.hash is None or '..' in entry.parts:
                continue
            content.update(json.dumps([name, str(entry)], separators=(',', ':')).encode())
            with distribution.locate_file(entry).open('rb') as stream:
                digest = hashlib.file_digest(stream, 'sha256').digest()
            content.update(digest)
    return dict(packages_sha256=content.hexdigest(), version=platform.python_version(), build=sys.version,
                platform=platform.system(), machine=platform.machine(),
                executable_sha256=hashlib.sha256(Path(sys.executable).read_bytes()).hexdigest(),
                packages={d.metadata['Name'].lower().replace('_', '-'): d.version
                          for d in distributions})


if __name__ == '__main__':
    print(json.dumps(observe(sys.argv[1] if len(sys.argv) > 1 else 'control'), sort_keys=True))


class ScientificUse:
    """Private receipt transport. The original App/CLI remains the process owner."""
    def __init__(self, directory, profile, consumer, approval, native=None):
        import os
        self.directory = Path(directory)
        self.identity = self.directory.name
        self.address = os.environ.get('PERO_SCIENTIFIC_USE_ADDRESS')
        self.token = os.environ.get('PERO_SCIENTIFIC_USE_TOKEN')
        self.approval = approval
        if not self.address or not self.token:
            raise ValueError('Managed scientific execution requires its Host EnvironmentUse owner')
        self.request(dict(operation='begin', id=self.identity, consumer=consumer,
                          approval=approval, profile=profile, native=native))

    def request(self, request):
        import socket
        host, port = self.address.rsplit(':', 1)
        if host != '127.0.0.1':
            raise ValueError('Scientific Use owner must be the local Host')
        with socket.create_connection((host, int(port)), timeout=10) as stream:
            stream.sendall(json.dumps(dict(token=self.token, request=request)).encode() + b'\n')
            with stream.makefile('rb') as response:
                raw = response.readline(65537)
        if len(raw)>65536 or not raw.endswith(b'\n'):
            raise ValueError('Invalid scientific Use receipt')
        value = json.loads(raw)
        if 'error' in value:
            raise ValueError(value['error'])
        (self.directory / 'environment-use.json').write_text(json.dumps(
            dict(use=value['value'], approval=self.approval), sort_keys=True))
        return value['value']

    def started(self, process):
        import os
        self.request(dict(operation='started', id=self.identity, pid=process.pid, parent=os.getpid()))
        process.stdin.write(b'execute\n')
        process.stdin.flush()
        process.stdin.close()

    def finish(self):
        return self.request(dict(operation='finish', id=self.identity))

    @staticmethod
    def stop(process, force=False):
        import os
        import signal
        try:
            os.killpg(process.pid, signal.SIGKILL if force else signal.SIGTERM)
        except ProcessLookupError:
            pass


def owner_environment():
    import os
    return {key:os.environ[key] for key in ('PERO_SCIENTIFIC_USE_ADDRESS', 'PERO_SCIENTIFIC_USE_TOKEN',
                                           'PERO_SCIENTIFIC_APPROVAL') if key in os.environ}
