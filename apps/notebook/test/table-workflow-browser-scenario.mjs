import { ensureMoreTools } from './notebook-browser-actions.mjs';
import { verifyRegistrationWaiver } from './registration-waiver-browser-scenario.mjs';
import assert from 'node:assert/strict';
import { resolve } from 'node:path';
import { expect } from '@playwright/test';

/** Real authenticated HTTP/SQLite workflow, run by the existing browser harness in CI. */
export async function verifyTableWorkflows(page, origin, output) {
  const button = (name, scope = page) => scope.getByRole('button', { name, exact: true });
  const select = async (label, option, scope = page) => {
    await button(label, scope).click();
    await page.getByRole('option', { name: option, exact: true }).click();
  };
  const request = async (path, body) => {
    const response = body === undefined ? await page.request.get(origin + path) : await page.request.post(origin + path, { data: body });
    assert.equal(response.ok(), true, await response.text());
    return response.json();
  };
  const columns = [{ id: 'name', name: 'Name', type: 'text', required: true, options: [], units: [] }, { id: 'note', name: 'Note', type: 'text', required: false, options: [], units: [] }];
  const source = { id: 'workflow-source', name: 'Workflow source', schema: { id: 'workflow-source-schema', revision: 1, columns }, rows: [{ id: 'source-row', cells: { name: 'Source A', note: '' } }] };
  const target = { id: 'workflow-target', name: 'Workflow target', schema: { id: 'workflow-target-schema', revision: 1, columns }, rows: [{ id: 'manual-row', cells: { name: 'Manual row', note: 'Keep this observation' } }] };
  const receipt = await request('/api/catalog/register', { submissionId: 'workflow-initial', table: source });
  const entry = await request('/api/entries', { document: { schemaVersion: 1, title: 'Collection and source workflow acceptance', content: { type: 'doc', content: [
    { type: 'inputTable', attrs: { blockId: 'workflow-input', table: target, receipts: [] } },
    { type: 'registrationTable', attrs: { blockId: 'workflow-registration', table: source, receipts: [receipt] } },
  ] } } });
  const published = await request('/api/templates', { name: 'Workflow protocol', description: 'Collection acceptance', kind: 'entry', collections: [], parameters: [], document: { schemaVersion: 1, title: 'Workflow protocol', content: { type: 'doc', content: [{ type: 'paragraph', attrs: { blockId: 'template-text' }, content: [{ type: 'text', text: 'Immutable protocol' }] }] } } });
  await page.setViewportSize({ width: 1320, height: 950 });
  await page.reload();
  await expect(page.getByRole('textbox', { name: 'Notebook title' })).toHaveValue(entry.document.title);
  await ensureMoreTools(page);
  await button('Templates').click();
  await button('Create collection').click();
  let dialog = page.getByRole('dialog', { name: 'Create collection', exact: true });
  await dialog.getByLabel('Collection name', { exact: true }).fill('Workflow methods');
  await button('Confirm organization change', dialog).click();
  await expect(dialog).toHaveCount(0);
  await select('Template collections', 'Workflow methods');
  await button('Create collection').click();
  dialog = page.getByRole('dialog', { name: 'Create collection', exact: true });
  await dialog.getByLabel('Collection name', { exact: true }).fill('PCR');
  await button('Confirm organization change', dialog).click();
  await select('Template collections', 'Workflow methods / PCR');
  await button('Move collection').click();
  dialog = page.getByRole('dialog', { name: 'Move collection', exact: true });
  await select('Destination', 'Library root', dialog);
  await button('Confirm organization change', dialog).click();
  await button('Rename collection').click();
  dialog = page.getByRole('dialog', { name: 'Rename collection', exact: true });
  await dialog.getByLabel('Collection name', { exact: true }).fill('PCR protocols');
  await button('Confirm organization change', dialog).click();
  await select('Template collections', 'All templates');
  await button('Workflow protocol · v1').click();
  await button('Move selected template').click();
  dialog = page.getByRole('dialog', { name: 'Move selected template', exact: true });
  await select('Destination', 'PCR protocols', dialog);
  await button('Confirm organization change', dialog).click();
  await select('Template collections', 'PCR protocols');
  await expect(button('Workflow protocol · v1')).toBeVisible();
  await button('Collection history').click();
  const library = await request('/api/template-collections');
  assert.equal(library.memberships[published.id], library.collections.find(item => item.name === 'PCR protocols').id);
  assert.equal((await request('/api/templates/' + published.id)).revision, 1);
  await page.screenshot({ path: resolve(output, 'workflows-template-collections-light.png'), fullPage: true });
  await page.getByRole('dialog', { name: 'Templates', exact: true }).getByRole('button', { name: 'Close', exact: true }).click();

  const input = page.locator('[data-kind=inputTable]');
  const registration = page.locator('[data-kind=registrationTable]');
  const open = async (scope = input) => {
    await button('Views, sources and archive', scope).click();
    return page.getByRole('dialog', { name: 'Views, sources and archive', exact: true });
  };
  dialog = await open();
  await dialog.getByLabel('View name', { exact: true }).fill('Names only');
  await dialog.getByRole('checkbox', { name: 'Note', exact: true }).uncheck();
  await button('Save view', dialog).click();
  await expect(button('Delete selected view', dialog)).toBeVisible();
  await button('Source mapping and resync', dialog).click();
  await dialog.getByLabel('Source schema ID', { exact: true }).fill(source.schema.id);
  await button('Preview source records', dialog).click();
  await expect(dialog.getByText(/1 of 1 catalog records/)).toBeVisible();
  await select('Source field for Name', 'Name (text)', dialog);
  await button('Save source and resync options', dialog).click();
  await expect(button('Preview resync', dialog)).toBeEnabled();
  await button('Preview resync', dialog).click();
  await expect(dialog.getByText('Source A', { exact: true })).toBeVisible();
  await button('Cancel preview', dialog).click();
  assert.equal((await request('/api/entries/' + entry.id + '/table-workflows/' + target.id)).baseline.length, 0);
  await button('Preview resync', dialog).click();
  await page.screenshot({ path: resolve(output, 'workflows-source-preview-light.png'), fullPage: true });
  await button('Confirm changes to draft', dialog).click();
  await expect(dialog.getByText('Resync applied to the table draft. Save the entry to keep these cells in its next revision.', { exact: true })).toBeVisible();
  await button('Close', dialog).click();
  await expect(input.getByLabel('Name, Row 1', { exact: true })).toHaveValue('Manual row');
  await expect(input.getByLabel('Name, Row 2', { exact: true })).toHaveValue('Source A');
  await button('Save revision').click();
  await expect(page.locator('.notebook-status')).toHaveText('Revision 2');
  await page.reload();
  await expect(input.getByLabel('Note, Row 1', { exact: true })).toHaveValue('Keep this observation');
  dialog = await open();
  await select('View', 'Names only', dialog);
  await button('Close', dialog).click();
  await expect(input.getByLabel('Note, Row 1', { exact: true })).toHaveCount(0);
  await button('All rows and columns', input).click();
  await input.getByLabel('Name, Row 2', { exact: true }).fill('Manual override');
  source.rows[0].cells.name = 'Source B';
  await request('/api/catalog/register', { submissionId: 'workflow-update', table: source });
  dialog = await open();
  await button('Source mapping and resync', dialog).click();
  await button('Preview resync', dialog).click();
  await expect(dialog.getByText('Keep manual value', { exact: true })).toBeVisible();
  await expect(dialog.getByText('Manual override', { exact: true })).toBeVisible();
  await page.setViewportSize({ width: 720, height: 900 });
  await page.evaluate(() => window.postMessage({ type: 'pero:app:context', context: { locale: 'en', dark: true, active: true } }, location.origin));
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'pero-dark');
  await page.screenshot({ path: resolve(output, 'workflows-manual-preservation-dark.png'), fullPage: true });
  await button('Confirm changes to draft', dialog).click();
  await expect(dialog.getByText('Resync applied to the table draft. Save the entry to keep these cells in its next revision.', { exact: true })).toBeVisible();
  await button('Close', dialog).click();
  await expect(input.getByLabel('Name, Row 2', { exact: true })).toHaveValue('Manual override');

  dialog = await open(registration);
  await button('Archive registered results', dialog).click();
  await button('Load record status', dialog).click();
  await dialog.getByLabel('Reason for this change', { exact: true }).fill('Retired source');
  await button('Confirm archive', dialog).click();
  await expect(dialog.getByText('Archived', { exact: true }).first()).toBeVisible();
  assert.equal((await request('/api/catalog/lookup?schemaId=' + source.schema.id)).total, 0);
  await dialog.getByLabel('Reason for this change', { exact: true }).fill('Rechecked source');
  await button('Confirm restore', dialog).click();
  await expect(dialog.getByText('Active', { exact: true }).first()).toBeVisible();
  await button('Close', dialog).click();
  assert.equal((await request('/api/catalog/lookup?schemaId=' + source.schema.id)).total, 1);
  assert.deepEqual((await request('/api/entries/' + entry.id + '/revisions/2')).document.content.content[1].attrs.receipts, [receipt]);
  await button('Save revision').click();
  await expect(page.locator('.notebook-status')).toHaveText('Revision 3');
  await page.reload();
  await expect(input.getByLabel('Name, Row 2', { exact: true })).toHaveValue('Manual override');
  // Import the same exported document into a second entry. IDs and catalog receipts stay portable,
  // but view/source settings and last-applied recovery belong only to their original entry.
  const firstRoot = '/api/entries/' + entry.id + '/table-workflows/' + target.id;
  const firstSettings = await request(firstRoot);
  const exported = await request('/api/entries/' + entry.id);
  const copied = await request('/api/entries', { document: exported.document });
  assert.notEqual(copied.id, entry.id);
  assert.equal(copied.document.content.content[0].attrs.table.id, target.id);
  const secondRoot = '/api/entries/' + copied.id + '/table-workflows/' + target.id;
  assert.deepEqual(await request(secondRoot), { revision: 0, views: [], source: null, baseline: [], lastApplied: null });
  await page.reload();
  const secondSettingsLoaded = page.waitForResponse(response => response.url() === origin + secondRoot && response.ok());
  dialog = await open();
  await secondSettingsLoaded;
  await dialog.getByLabel('View name', { exact: true }).fill('Independent imported view');
  await button('Save view', dialog).click();
  await button('Source mapping and resync', dialog).click();
  await expect(dialog.getByLabel('Source schema ID', { exact: true })).toHaveValue('');
  await expect(button('Recover last confirmed resync into this unchanged draft', dialog)).toHaveCount(0);
  await button('Close', dialog).click();
  assert.deepEqual(await request(firstRoot), firstSettings);
  const secondSettings = await request(secondRoot);
  assert.equal(secondSettings.views[0].name, 'Independent imported view');
  assert.equal(secondSettings.source, null);
  assert.equal(secondSettings.lastApplied, null);
  assert.equal((await request('/api/entries/' + copied.id)).revision, 1);
  assert.equal((await request('/api/entries/' + entry.id)).revision, 3);
  await page.setViewportSize({ width: 1320, height: 950 });
  await page.evaluate(() => window.postMessage({ type: 'pero:app:context', context: { locale: 'en', dark: false, active: true } }, location.origin));
  await verifyRegistrationWaiver(page, origin, output);
}
