import { closeInsertMenu, createNotebook, ensureMoreTools, openNotebookMenu } from './notebook-browser-actions.mjs';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { resolve } from 'node:path';
import { expect } from '@playwright/test';

// Uses the real Notebook editor and SQLite backend supplied by notebook-browser.mjs.
// This checks local text integrity and retained revisions, not external authorship.
export async function verifySourceExcerpts(page, origin, output) {
  const button = (name, scope = page) => scope.getByRole('button', { name, exact: true });
  const title = 'Source excerpt acceptance';
  const bytes = Buffer.from('\ufeffA🧪e\u0301\r\n终\rLast');
  await page.setViewportSize({ width: 1320, height: 950 });
  await page.evaluate(() => window.postMessage({ type: 'pero:app:context', context: { locale: 'en', dark: false, active: true } }, location.origin));
  const created = await createNotebook(page, origin, title);
  await page.locator('input[type=file]:not([accept])').setInputFiles({ name: 'pinned-notes.txt', mimeType: 'text/plain', buffer: bytes });
  const attachment = page.locator('[data-kind=attachment]').first();
  await expect(button('Download file', attachment)).toBeEnabled();
  const open = async () => {
    await ensureMoreTools(page);
    await button('Insert source excerpt').click();
    const dialog = page.getByRole('dialog');
    await button('Source attachment', dialog).click();
    await page.screenshot({ path: resolve(output, 'source-excerpt-picker-light.png') });
    await page.getByRole('option', { name: 'pinned-notes.txt · text/plain', exact: true }).click();
    await expect(dialog.getByLabel('Source text (read-only)', { exact: true })).toHaveValue('\ufeffA🧪e\u0301\n终\nLast');
    return dialog;
  };
  let dialog = await open();
  await button('Cancel', dialog).click();
  await expect(page.locator('[data-kind=sourceExcerpt]')).toHaveCount(0);
  dialog = await open();
  await dialog.getByLabel('Excerpt label', { exact: true }).fill('Exact retained source');
  await dialog.getByLabel('Source text (read-only)', { exact: true }).evaluate(node => { node.focus(); node.setSelectionRange(2, 8); });
  await button('Use highlighted text', dialog).click();
  await expect(dialog.getByLabel('Start offset (codepoints, inclusive)', { exact: true })).toHaveValue('2');
  await expect(dialog.getByLabel('End offset (codepoints, exclusive)', { exact: true })).toHaveValue('8');
  await button('Insert source excerpt', dialog).click();
  await expect(dialog).toHaveCount(0);
  await closeInsertMenu(page);
  const block = page.locator('[data-kind=sourceExcerpt]').first();
  await expect(block.getByText('Retained text integrity verified.', { exact: true })).toBeVisible();
  await expect(block.getByText('Original attachment is available and unchanged.', { exact: true })).toBeVisible();
  await button('Save revision').click();
  await expect(page.locator('.notebook-status')).toHaveText('Revision 2');
  await page.screenshot({ path: resolve(output, 'source-excerpt-light.png'), fullPage: true });
  const savedResponse = await page.request.get(`${origin}/api/entries/${created.id}`);
  assert.equal(savedResponse.ok(), true, await savedResponse.text());
  const saved = await savedResponse.json();
  assert.equal(saved.document.title, title);
  assert.equal(saved.revision, 2);
  const nodes = []; const visit = node => { nodes.push(node); node.content?.forEach(visit); }; visit(saved.document.content);
  const snapshot = nodes.find(node => node.type === 'sourceExcerpt').attrs.excerpt;
  assert.equal(snapshot.quote, '🧪e\u0301\r\n终');
  assert.equal(snapshot.version, createHash('sha256').update(bytes).digest('hex'));
  assert.deepEqual(Buffer.from(snapshot.text), bytes);
  await button('Update excerpt', block).click();
  dialog = page.getByRole('dialog');
  await dialog.getByLabel('Start offset (codepoints, inclusive)', { exact: true }).fill('1');
  await dialog.getByLabel('End offset (codepoints, exclusive)', { exact: true }).fill('2');
  await button('Cancel', dialog).click();
  await expect(block.locator('blockquote')).toHaveText('🧪e\u0301\r\n终');
  await button('Block actions', attachment).click();
  await page.getByRole('menuitem', { name: 'Remove block', exact: true }).click();
  await expect(block.getByText('Original attachment is no longer in this notebook. The retained text and quote remain available.', { exact: true })).toBeVisible();
  const downloading = page.waitForEvent('download');
  await button('Download retained source', block).click();
  const chunks = []; for await (const chunk of await (await downloading).createReadStream()) chunks.push(chunk);
  assert.deepEqual(Buffer.concat(chunks), bytes);
  await button('Save revision').click(); await expect(page.locator('.notebook-status')).toHaveText('Revision 3');
  await page.evaluate(() => window.postMessage({ type: 'pero:app:context', context: { locale: 'en', dark: true, active: true } }, location.origin));
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'pero-dark');
  await page.setViewportSize({ width: 600, height: 900 });
  const navigation = button('Notebooks'); if (await navigation.getAttribute('aria-expanded') === 'true') await navigation.click();
  await page.screenshot({ path: resolve(output, 'source-excerpt-retained-narrow-dark.png'), fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.setViewportSize({ width: 1320, height: 950 });
  await openNotebookMenu(page, 'file');
  await button('Revision history').click(); await button('Revision 2').click();
  await expect(button('Update excerpt', block)).toHaveCount(0);
  await expect(button('Download retained source', block)).toBeEnabled();
  await expect(page.locator('[data-kind=attachment]')).toHaveCount(1);
  await button('Return to current notebook').click();
  await expect(page.locator('.notebook-status')).toHaveText('Revision 3');
  await expect(button('Update excerpt', block)).toBeVisible();
}
