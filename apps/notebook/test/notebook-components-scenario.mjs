import { createNotebook } from './notebook-browser-actions.mjs';
import assert from 'node:assert/strict';
import { resolve } from 'node:path';
import { expect } from '@playwright/test';

// Uses the real SQLite backend of notebook-browser.mjs. The only Host fixture is
// its existing theme-context transport. This does not establish native Host,
// external model, external inventory, or App action acceptance.
export async function verifyNotebookComponents(page, origin, output) {
  const button = (name, scope = page) => scope.getByRole('button', { name, exact: true });
  const tab = name => page.getByRole('tab', { name, exact: true }).click();
  const select = async (label, value, scope = page) => {
    await button(label, scope).click();
    await page.getByRole('option', { name: value, exact: true }).click();
  };
  const insert = async name => {
    await button('Insert block').click();
    await page.getByRole('menuitem', { name, exact: true }).click();
  };
  const shot = name => page.screenshot({ path: resolve(output, `components-${name}.png`), fullPage: true });
  const theme = dark => page.evaluate(dark => window.postMessage({ type: 'pero:app:context',
    context: { locale: 'en', dark, active: true } }, location.origin), dark);
  const json = async path => {
    const response = await page.request.get(origin + path);
    assert.equal(response.ok(), true, await response.text());
    return response.json();
  };
  const save = async revision => {
    await button('Save revision').click();
    await expect(page.locator('.notebook-status')).toHaveText(`Revision ${revision}`);
  };
  await page.setViewportSize({ width: 1320, height: 950 });
  await theme(false);
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'pero-light');
  const title = 'Component acceptance';
  const created = await createNotebook(page, origin, title);
  await page.getByRole('textbox', { name: 'Notebook content' }).fill('Independent local component acceptance');
  await insert('Section');
  const section = page.locator('[data-kind=section]').first();
  await section.getByRole('textbox', { name: 'Section title' }).fill('Sample preparation');
  await section.getByLabel('Section date').fill('2026-11-09');
  await button('Collapse section', section).click();
  await expect(button('Expand section', section)).toHaveAttribute('aria-expanded', 'false');
  await button('Expand section', section).click();
  const attachmentInput = page.locator('input[type=file]:not([accept])');
  await attachmentInput.setInputFiles({ name: 'oversize.txt', mimeType: 'text/plain', buffer: Buffer.alloc(512 * 1024 + 1) });
  await expect(page.getByText('This file exceeds the 512 KiB attachment limit.')).toBeVisible();
  await expect(page.locator('[data-kind=attachment]')).toHaveCount(0);
  const bytes = Buffer.from('Actual local attachment bytes\n');
  await attachmentInput.setInputFiles({ name: 'sample-notes.txt', mimeType: 'text/plain', buffer: bytes });
  const attachment = page.locator('[data-kind=attachment]').first();
  await attachment.getByLabel('Attachment caption').fill('Sample input record');
  const downloading = page.waitForEvent('download');
  await button('Download file', attachment).click();
  const chunks = [];
  for await (const chunk of await (await downloading).createReadStream()) chunks.push(chunk);
  assert.deepEqual(Buffer.concat(chunks), bytes);

  await tab('Metadata');
  await page.getByLabel('Project label', { exact: true }).fill('Component verification');
  await page.getByLabel('Author label', { exact: true }).fill('Local tester');
  await page.getByLabel('New tag', { exact: true }).fill('acceptance');
  await button('Add tag').click();
  await page.getByLabel('New tag', { exact: true }).fill('acceptance');
  await button('Add tag').click();
  await expect(page.getByText('That tag already exists.')).toBeVisible();
  // Global history is accessible from Notes, but restores metadata as well.
  await tab('Notes');
  await button('Undo').click();
  await tab('Metadata');
  await expect(button('Remove tag acceptance')).toHaveCount(0);
  await tab('Notes');
  await button('Redo').click();
  await tab('Metadata');
  await expect(button('Remove tag acceptance')).toBeVisible();
  await shot('metadata-desktop-light');

  await tab('Procedures');
  await button('Add procedure').click();
  await page.getByLabel('Procedure title', { exact: true }).fill('Six procedure kinds');
  await button('Add material').click();
  await page.getByLabel('Material 1', { exact: true }).fill('Buffer');
  await page.getByLabel('Quantity 1', { exact: true }).fill('10 mL');
  const kinds = ['Header', 'Description', 'Step', 'Image', 'Table', 'Timer'];
  const procedureSteps = page.getByRole('region', { name: 'Steps', exact: true }).locator('.notebook-procedure-steps > li');
  for (const [index, kind] of kinds.entries()) {
    await button('Add step').click();
    const step = procedureSteps.nth(index);
    await select('Step kind', kind, step);
    await step.getByRole('textbox', { name: 'Step formatting', exact: true }).fill(`${kind} instructions`);
    await step.getByLabel(`Planned minutes ${index + 1}`, { exact: true }).fill('2');
  }
  await expect(page.getByText('Total planned: 12 minutes', { exact: true })).toBeVisible();
  await page.getByLabel('Planned minutes 1', { exact: true }).fill('-1');
  await expect(page.getByText('Enter 0–10,080 minutes, or leave blank.')).toBeVisible();
  await page.getByLabel('Planned minutes 1', { exact: true }).fill('2');
  const imageStep = procedureSteps.nth(3);
  await imageStep.locator('input[type=file]').setInputFiles({ name: 'pixel.png', mimeType: 'image/png',
    buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+a9S8AAAAASUVORK5CYII=', 'base64') });
  await expect(imageStep.locator('[data-kind=attachment] img')).toBeVisible();
  const tableStep = procedureSteps.nth(4);
  await button('Insert editable table', tableStep).click();
  await tableStep.locator('[data-cell=A1]').fill('7');
  const timerStep = procedureSteps.nth(5);
  await button('Start timer', timerStep).click();
  await expect(button('Start timer', timerStep)).toBeDisabled();
  await expect(timerStep.locator('output')).not.toHaveText('Actual elapsed: 0.0 seconds');
  await button('Pause timer', timerStep).click();
  await expect(button('Pause timer', timerStep)).toBeDisabled();
  await button('Reset timer', timerStep).click();
  await expect(timerStep.locator('output')).toHaveText('Actual elapsed: 0.0 seconds');
  await button('Remove procedure').click();
  await button('Cancel', page.getByRole('dialog')).click();
  await expect(procedureSteps).toHaveCount(6);
  await shot('procedures-desktop-light');
  await save(2);
  const entries = await json('/api/entries');
  const summary = entries.entries.find(entry => entry.id === created.id);
  assert.ok(summary, `Created notebook ${created.id} missing from catalog: ${JSON.stringify(entries.entries)}`);
  assert.equal(summary.title, title);
  const id = created.id;
  const saved = () => json(`/api/entries/${id}`);
  // Older snapshots omit kind for ordinary steps; compare the domain's effective kinds.
  assert.deepEqual((await saved()).document.procedures[0].steps.map(step => step.kind ?? 'step'), kinds.map(kind => kind.toLowerCase()));
  await tab('Metadata');
  await page.getByLabel('Project label', { exact: true }).fill('Durable draft project');
  await expect.poll(async () => (await json(`/api/entries/${id}/draft`)).draft?.document.metadata.project).toBe('Durable draft project');
  await page.reload();
  await expect(page.getByRole('textbox', { name: 'Notebook title' })).toHaveValue(title);
  await tab('Metadata');
  await expect(page.getByLabel('Project label', { exact: true })).toHaveValue('Durable draft project');
  assert.equal((await saved()).revision, 2);
  await tab('Notes');

  await page.getByRole('textbox', { name: 'Notebook content', exact: true }).press('ControlOrMeta+End');
  await insert('Registration table');
  const registration = page.locator('[data-kind=registrationTable]');
  await expect(button('Submit rows to local catalog', registration)).toBeDisabled();
  await registration.getByRole('textbox', { name: 'Table name', exact: true }).fill('Acceptance catalog');
  await registration.getByRole('textbox', { name: 'Name, Row 1', exact: true }).fill('Acceptance sample');
  await button('Submit rows to local catalog', registration).click();
  await expect(registration.getByText('Submission receipts (1)', { exact: true })).toBeVisible();
  // A second unchanged submission must retain one receipt and one catalog row.
  await button('Confirm snapshot in this catalog', registration).click();
  await expect(registration.getByText('Submission receipts (1)', { exact: true })).toBeVisible();
  await insert('Lookup table');
  const lookup = page.locator('[data-kind=lookupTable]');
  await lookup.getByLabel('Search catalog records', { exact: true }).fill('Acceptance sample');
  await button('Refresh from local catalog', lookup).click();
  await expect(lookup).toContainText('showing 1 of 1 records');
  await lookup.getByLabel('Search catalog records', { exact: true }).fill('No such sample');
  await expect(lookup).toContainText('The query changed. Showing the previous query snapshot until you refresh.');
  await expect(lookup).toContainText('Acceptance sample');
  await shot('catalog-frozen-query');
  // Publish the selected query block and insert two independent copies.
  await lookup.getByLabel('Search catalog records', { exact: true }).click();
  await button('More tools').click();
  await button('Templates').click();
  let dialog = page.getByRole('dialog');
  await button('Publish from current content', dialog).click();
  await select('Template scope', 'Selected section / block', dialog);
  await dialog.getByLabel('Name', { exact: true }).fill('Frozen query fragment');
  await button('Publish immutable revision', dialog).click();
  await expect(button('Insert independent fragment', dialog)).toBeEnabled();
  await shot('template-published');
  await button('Insert independent fragment', dialog).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  if (!await button('Hide more tools').count()) await button('More tools').click();
  await button('Templates').click();
  dialog = page.getByRole('dialog');
  await button('Frozen query fragment · v1', dialog).click();
  await button('Insert independent fragment', dialog).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await save(3);
  const lookups = [];
  const visit = node => { if (node.type === 'lookupTable') lookups.push(node); node.content?.forEach(visit); };
  visit((await saved()).document.content);
  assert.equal(lookups.length, 3);
  assert.equal(new Set(lookups.map(node => node.attrs.blockId)).size, 3);
  const instances = lookups.filter(node => node.attrs.templateOrigin);
  assert.equal(instances.length, 2);
  assert.notEqual(instances[0].attrs.templateOrigin.instanceId, instances[1].attrs.templateOrigin.instanceId);
  for (const node of lookups) {
    assert.equal(node.attrs.query.text, 'No such sample');
    assert.equal(node.attrs.snapshot.query.text, 'Acceptance sample');
    assert.equal(node.attrs.snapshot.records.length, 1);
  }

  await insert('Mixture preparation');
  const mixture = page.locator('[data-kind=mixturePrep]');
  await button('Save recipe revision', mixture).click();
  await expect(mixture).toContainText('Name, positive target and at least one ingredient are required.');
  await mixture.getByLabel('Recipe name', { exact: true }).fill('Buffer dilution');
  await mixture.getByLabel('Final target', { exact: true }).fill('10');
  await button('Add ingredient', mixture).click();
  await mixture.getByLabel('Material / batch reference', { exact: true }).fill('Buffer lot A');
  await mixture.getByLabel('Planned quantity', { exact: true }).fill('10');
  await button('Save recipe revision', mixture).click();
  await mixture.getByLabel('Operator (self-reported)', { exact: true }).fill('Local tester');
  await button('Record actual preparation', mixture).click();
  await expect(mixture).toContainText('planned amounts are not measurements');
  await mixture.getByLabel('Measured quantity', { exact: true }).fill('9.8');
  await mixture.getByLabel('Actual output identifier', { exact: true }).fill('Batch acceptance');
  await button('Record actual preparation', mixture).click();
  await expect(mixture.locator('details')).toHaveCount(1);
  await mixture.locator('summary').click();
  await expect(mixture.locator('details')).toContainText('Measured quantity: 9.8');
  await shot('mixture-planned-and-measured');

  await button('More tools').click();
  await button('Scientific tools').click();
  dialog = page.getByRole('dialog');
  await dialog.getByRole('combobox', { name: 'Scientific tools', exact: true }).selectOption('sequence');
  await dialog.getByLabel('Sequence (IUPAC, up to 20,000 nt)', { exact: true }).fill('ATGAAATAA');
  await button('Calculate', dialog).click();
  await button('Insert snapshot', dialog).click();
  await expect(dialog).toContainText('Snapshot inserted as new content.');
  await button('Insert snapshot', dialog).click();
  await expect(dialog).toContainText('This snapshot has already been inserted.');
  await shot('scientific-snapshot');
  await dialog.getByRole('combobox', { name: 'Scientific tools', exact: true }).selectOption('ai');
  await expect(dialog).toContainText('No configured Host agent is available.');
  await expect(button('Generate candidates', dialog)).toBeDisabled();
  await shot('ai-host-unavailable');
  await button('Close', dialog).click();
  await save(4);
  const allNodes = [];
  const collect = node => { allNodes.push(node); node.content?.forEach(collect); };
  collect((await saved()).document.content);
  const storedMixture = allNodes.find(node => node.type === 'mixturePrep').attrs.mixture;
  assert.equal(storedMixture.records.length, 1);
  assert.equal(storedMixture.records[0].recipe.ingredients[0].target.value, 10);
  assert.equal(Object.values(storedMixture.records[0].actual)[0].value, 9.8);
  const scienceSnapshots = allNodes.filter(node => node.type === 'codeBlock' &&
    node.content?.some(text => text.text?.includes('ATGAAATAA')));
  assert.equal(scienceSnapshots.length, 1);

  await tab('Review and activity');
  await button('Start comment thread').click();
  dialog = page.getByRole('dialog');
  await expect(button('Save record', dialog)).toBeDisabled();
  await dialog.getByLabel('Comment', { exact: true }).fill('Cancelled comment');
  await button('Cancel', dialog).click();
  await expect(page.getByText('Cancelled comment', { exact: true })).toHaveCount(0);
  await button('Start comment thread').click();
  dialog = page.getByRole('dialog');
  await dialog.getByLabel('Comment', { exact: true }).fill('Check sample provenance');
  await button('Save record', dialog).click();
  await expect(page.getByText('Check sample provenance', { exact: true })).toBeVisible();
  await button('Resolve thread').click();
  await expect(button('Reopen thread')).toBeVisible();
  await tab('Local tasks');
  await button('Add local task').click();
  dialog = page.getByRole('dialog');
  await dialog.getByLabel('Task title', { exact: true }).fill('Verify local measurements');
  await button('Save record', dialog).click();
  await expect(page.getByText('Verify local measurements', { exact: true })).toBeVisible();
  await tab('Human review');
  await page.getByRole('button', { name: 'Request local self-review · r4', exact: true }).click();
  dialog = page.getByRole('dialog');
  await button('Save record', dialog).click();
  await button('Record my approval').click();
  dialog = page.getByRole('dialog');
  await dialog.getByLabel('Review note or decision reason', { exact: true }).fill('Reviewed the pinned local snapshot');
  await expect(button('Confirm local action', dialog)).toBeDisabled();
  await dialog.getByRole('checkbox').check();
  await button('Confirm local action', dialog).click();
  await expect(page.getByText('Approved locally', { exact: true })).toBeVisible();
  await shot('review-local-approval');
  await tab('Metadata');
  await page.getByLabel('Project label', { exact: true }).fill('Revised after local review');
  await save(5);
  await tab('Review and activity');
  await tab('Human review');
  await expect(page.getByText('Older revision; does not review the latest content', { exact: true })).toBeVisible();
  const records = await json(`/api/entries/${id}/review-workspace`);
  assert.equal(records.threads.length, 1);
  assert.equal(records.tasks.length, 1);
  assert.equal(records.reviews.length, 1);
  assert.equal(records.reviews[0].stale, true);
  await theme(true);
  await page.setViewportSize({ width: 600, height: 900 });
  const navigation = button('Notebooks');
  if (await navigation.getAttribute('aria-expanded') === 'true') await navigation.click();
  await shot('review-stale-narrow-dark');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);

  await page.setViewportSize({ width: 1320, height: 950 });
  await button('Revision history').click();
  await button('Revision 4').click();
  await tab('Metadata');
  await expect(page.getByLabel('Project label', { exact: true })).toHaveAttribute('readonly', '');
  await tab('Procedures');
  await expect(button('Add procedure')).toHaveCount(0);
  await expect(button('Start timer')).toHaveCount(0);
  await expect(procedureSteps.first().getByRole('textbox', { name: 'Step formatting', exact: true })).toHaveAttribute('contenteditable', 'false');
  await tab('Review and activity');
  await expect(button('Start comment thread')).toHaveCount(0);
  await tab('Notes');
  await expect(button('Save recipe revision')).toHaveCount(0);
  await expect(button('Submit rows to local catalog')).toHaveCount(0);
  await shot('readonly-saved-revision');
  await button('Return to current notebook').click();
  await theme(false);
}
