import { createNotebook } from './notebook-browser-actions.mjs';
import assert from 'node:assert/strict';
import { resolve } from 'node:path';
import { expect } from '@playwright/test';

// Exact-product browser acceptance, using notebook-browser.mjs's real SQLite backend.
// No physical inventory, chemistry toolkit or external registry is simulated here.
export async function verifyScientificDesigns(page, origin, output) {
  const button = (name, scope = page) => scope.getByRole('button', { name, exact: true });
  await page.setViewportSize({ width: 1320, height: 950 });
  await createNotebook(page, origin, 'Scientific design acceptance');
  await button('Insert reaction sketch').click();
  const reaction = page.locator('[data-kind=reactionScheme]').first();
  await reaction.getByLabel('Name', { exact: true }).fill('Explicit graph conversion');
  await button('Add molecule', reaction).click();
  await reaction.getByLabel('Molecule Name', { exact: true }).fill('Starting graph');
  await button('Add atom', reaction).click();
  await reaction.getByLabel('Element', { exact: true }).selectOption('O');
  await reaction.getByLabel('Atom X (0–600)', { exact: true }).fill('180');
  await button('Add atom', reaction).click();
  const from = await reaction.getByLabel('Bond to atom', { exact: true }).locator('option').nth(1).getAttribute('value');
  await reaction.getByLabel('Bond to atom', { exact: true }).selectOption(from);
  await reaction.getByLabel('Bond order', { exact: true }).selectOption('2');
  await button('Set bond', reaction).click();
  await button('Save local reaction record', reaction).click();
  await expect(reaction.getByRole('alert')).toContainText('at least one reactant and one product');
  await button('Add molecule', reaction).click();
  await reaction.getByLabel('Molecule Name', { exact: true }).fill('Product graph');
  await button('Add atom', reaction).click();
  await button('Save local reaction record', reaction).click();
  await expect(reaction.getByText(/Saved local record:/)).toBeVisible();
  await expect(button('Save next local revision', reaction)).toBeDisabled();
  await button('Embed saved molecule', reaction).click();
  const chemical = page.locator('[data-kind=chemical]').first();
  await expect(chemical.getByText(/Extracted from recorded/)).toBeVisible();
  const download = page.waitForEvent('download');
  await button('Download chemical JSON', chemical).click();
  const chunks = [];
  for await (const chunk of await (await download).createReadStream()) chunks.push(chunk);
  const downloaded = Buffer.concat(chunks), exported = JSON.parse(downloaded.toString());
  assert.equal(exported.format, 'pero-chemical/1'); assert.equal(exported.chemical.source.revision, 1);
  await chemical.getByLabel('Chemical JSON file', { exact: true }).setInputFiles({ name: 'chemical.json', mimeType: 'application/json', buffer: downloaded });
  await expect(chemical.getByText(/Extracted from recorded/)).toBeVisible();
  await page.screenshot({ path: resolve(output, 'scientific-graph-light.png'), fullPage: true });

  await button('Scientific tools').click();
  await page.getByLabel('Scientific tools', { exact: true }).selectOption('plate');
  const dialog = page.getByRole('dialog');
  await dialog.getByText('Reusable plate designs', { exact: true }).click();
  await dialog.getByLabel('Plate design name', { exact: true }).fill('Reusable controls');
  await dialog.getByLabel('Plate barcode', { exact: true }).fill('PLATE-7');
  await dialog.getByLabel('Well capacity (µL, optional)', { exact: true }).fill('20');
  await dialog.getByLabel('Group name', { exact: true }).fill('Control');
  await button('Assign selected wells', dialog).click();
  await button('Save as new reusable design', dialog).click();
  await expect(dialog.getByText(/Saved plate design revision:/)).toBeVisible();
  await button('Clear selected wells', dialog).click();
  await expect(button('A1', dialog)).toHaveAttribute('title', 'A1: ∅');
  await button('Load selected design', dialog).click();
  await button('Cancel', dialog).click();
  await expect(button('A1', dialog)).toHaveAttribute('title', 'A1: ∅');
  await button('Load selected design', dialog).click();
  await button('Replace working layout', dialog).click();
  await expect(button('Replace working layout', dialog)).toHaveCount(0);
  await expect(button('A1', dialog)).toHaveAttribute('title', 'A1: Control');
  await expect(dialog.getByLabel('Plate barcode', { exact: true })).toHaveValue('PLATE-7');
  await button('Insert snapshot', dialog).click(); await button('Close', dialog).click();
  await button('Save revision').click(); await expect(page.locator('.notebook-status')).toHaveText('Revision 2');
  const records = await (await page.request.get(`${origin}/api/scientific/reactions`)).json();
  assert.ok(records.records.some(record => record.definition.name === 'Explicit graph conversion'));
  const plates = await (await page.request.get(`${origin}/api/scientific/plates`)).json();
  assert.ok(plates.records.some(record => record.definition.name === 'Reusable controls' && record.definition.metadata.barcode === 'PLATE-7'));
  await page.reload(); await expect(page.locator('[data-kind=reactionScheme]')).toHaveCount(1); await expect(page.locator('[data-kind=chemical]')).toHaveCount(1);
  await page.setViewportSize({ width: 520, height: 900 });
  await page.evaluate(() => window.postMessage({ type: 'pero:app:context', context: { locale: 'en', dark: true, active: true } }, location.origin));
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'pero-dark');
  await page.screenshot({ path: resolve(output, 'scientific-graph-narrow-dark.png'), fullPage: true });
}
