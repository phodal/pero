import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { execFileSync } from 'node:child_process';

const root = resolve(import.meta.dirname, '..');
const kit = resolve(process.env.PERO_GPUI_KIT_PATH || resolve(root, '../../test/gpui-kit'));
const catalog = JSON.parse(await readFile(resolve(root, 'packages/icons/catalog.json'), 'utf8'));
const entries = Object.entries(catalog);
const variant = name => name.split('-').map(part => part[0].toUpperCase() + part.slice(1)).join('');
const names = (name, icon) => [name, ...(icon.aliases || [])];
const kitNames = entries.filter(([, icon]) => icon.kit).map(([, icon]) => icon.kit);
const header = '// Generated by scripts/generate-icons.mjs from packages/icons/catalog.json.\n';

const rust = `${header}use gpui_kit::*;
use std::borrow::Cow;

gpui_kit::assets::icon_assets!(SelectedKitIcons, [${kitNames.join(', ')}]);

/// Shared, bundled action and object icons. Names remain stable across renderers.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum UiIcon {
${entries.map(([name]) => `    ${variant(name)},`).join('\n')}
}

impl UiIcon {
    pub fn named(name: &str) -> Self {
        Self::lookup(name).unwrap_or(Self::LayoutGrid)
    }

    fn lookup(name: &str) -> Option<Self> {
        match name {
${entries.map(([name, icon]) => `            ${names(name, icon).map(value => JSON.stringify(value)).join(' | ')} => Some(Self::${variant(name)}),`).join('\n')}
            _ => None,
        }
    }

    pub fn path(self) -> &'static str {
        match self {
${entries.map(([name]) => `            Self::${variant(name)} => "icons/${name}.svg",`).join('\n')}
        }
    }

    pub fn element(self) -> Svg {
        svg().path(self.path())
    }
}

pub struct UiAssets;
impl AssetSource for UiAssets {
    fn load(&self, path: &str) -> anyhow::Result<Option<Cow<'static, [u8]>>> {
        let icon = path.strip_prefix("icons/").and_then(|name| name.strip_suffix(".svg")).and_then(UiIcon::lookup);
        Ok(match icon {
${entries.map(([name, icon]) => icon.kit
  ? `            Some(UiIcon::${variant(name)}) => SelectedKitIcons.load("icons/${name}.svg")?,`
  : `            Some(UiIcon::${variant(name)}) => Some(Cow::Borrowed(include_bytes!("../../../web/public/icons/${icon.source || name}.svg"))),`).join('\n')}
            None => None,
        })
    }

    fn list(&self, prefix: &str) -> anyhow::Result<Vec<SharedString>> {
        Ok([
${entries.map(([name]) => `            UiIcon::${variant(name)},`).join('\n')}
        ].into_iter().map(UiIcon::path).filter(|path| path.starts_with(prefix)).map(Into::into).collect())
    }
}
`;

// Convert existing SVG artwork to static JSX; no SVG parser or network is needed at runtime.
const jsxAttribute = name => name.replace(/[-:]([a-z])/g, (_, character) => character.toUpperCase()).replace(/^class$/, 'className');
const shapes = [];
for (const [name, icon] of entries) {
  const source = icon.kit
    ? resolve(kit, `crates/assets/assets/icons/${name}.svg`)
    : resolve(root, `web/public/icons/${icon.source || name}.svg`);
  const svg = (await readFile(source, 'utf8')).replace(/<!--[\s\S]*?-->/g, '').trim();
  const match = /^<svg\b([^>]*)>([\s\S]*)<\/svg>$/.exec(svg);
  if (!match) throw new Error(`Invalid SVG icon: ${source}`);
  const attrs = Object.fromEntries([...match[1].matchAll(/([\w:-]+)="([^"]*)"/g)]
    .filter(([, key]) => !['xmlns', 'width', 'height'].includes(key))
    .map(([, key, value]) => [jsxAttribute(key), value]));
  const children = match[2].trim().replace(/([\w:-]+)=/g, (_, key) => `${jsxAttribute(key)}=`).replace(/\s+/g, ' ');
  const origin = icon.kit ? `gpui-kit/assets/icons/${name}.svg (Lucide, LICENSE-LUCIDE)` : `web/public/icons/${icon.source || name}.svg (LICENSE.txt)`;
  shapes.push(`  // ${origin}\n  ${JSON.stringify(name)}: { props: ${JSON.stringify(attrs)}, children: <>${children}</> },`);
}
const aliases = entries.flatMap(([name, icon]) => (icon.aliases || []).map(alias => `  ${JSON.stringify(alias)}: ${JSON.stringify(name)},`));
const licenses = await Promise.all([
  'web/public/icons/LICENSE.txt', 'packages/icons/LICENSE-LUCIDE',
].map(path => readFile(resolve(root, path), 'utf8')));
const tsx = `${header}/*! Bundled icon artwork licenses:\n${licenses.join('\n\n')}\n*/
import React from 'react';

const artwork = {
${shapes.join('\n')}
} satisfies Record<string, { props: React.SVGProps<SVGSVGElement>; children: React.ReactNode }>;

const aliases = {
${aliases.join('\n')}
} as const;

export type IconName = keyof typeof artwork | keyof typeof aliases;
export function iconArtwork(name: string) {
  const canonical = Object.hasOwn(aliases, name) ? aliases[name as keyof typeof aliases] : name;
  return Object.hasOwn(artwork, canonical) ? artwork[canonical as keyof typeof artwork] : artwork['layout-grid'];
}
`;

for (const [path, contents] of [
  ['crates/pero-chat-ui/src/assets.rs', execFileSync('rustfmt', ['--edition', '2024', '--emit', 'stdout'], { input: rust, encoding: 'utf8' })],
  ['packages/app-sdk/src/icons.generated.tsx', tsx],
]) {
  const file = resolve(root, path);
  if (process.argv.includes('--check')) {
    if (await readFile(file, 'utf8') !== contents) throw new Error(`Regenerate icons: node scripts/generate-icons.mjs (${path})`);
  } else {
    await writeFile(file, contents);
  }
}
console.log(`${process.argv.includes('--check') ? 'Checked' : 'Generated'} ${entries.length} shared icons (${kitNames.length} selected Kit assets).`);
