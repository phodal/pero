import { readFile, writeFile } from 'node:fs/promises';
const root = new URL('../../packages/app-sdk/src/tokens/', import.meta.url);
const names = ['theme-light', 'theme-dark', 'theme-contrast', 'structure'];
const css = (await Promise.all(names.map(name => readFile(new URL(`${name}.css`, root), 'utf8')))).join('');
const module = '// Generated by scripts/build/app-sdk-tokens.mjs.\nexport const TOKENS_CSS = ' + JSON.stringify(css) + ';\n';
const output = new URL('tokens-css.mjs', root);
if (process.argv.includes('--check')) {
  if (await readFile(output, 'utf8') !== module) throw new Error('Stale SDK tokens; run node scripts/build/app-sdk-tokens.mjs');
} else await writeFile(output, module);
