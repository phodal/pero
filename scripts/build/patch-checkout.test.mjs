import assert from 'node:assert/strict';
import { execFileSync, spawnSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { test } from 'node:test';

// Exercise Git's real checkout conversion, independent of the host platform.
test('pinned GPUI patch retains canonical bytes with Windows checkout defaults', t => {
  const canonical = readFileSync(new URL('../../patches/gpui-pre-web-0.3.10-ime.patch', import.meta.url));
  const attributes = readFileSync(new URL('../../.gitattributes', import.meta.url));
  const root = mkdtempSync(join(tmpdir(), 'pero-patch-checkout-'));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  const git = (...args) => execFileSync('git', args, { cwd: root, stdio: 'pipe' });
  git('init', '-q');
  git('config', '--local', 'core.autocrlf', 'true');
  git('config', '--local', 'core.safecrlf', 'false');
  const emptyAttributes = join(root, 'empty-attributes');
  writeFileSync(emptyAttributes, '');
  git('config', '--local', 'core.attributesFile', emptyAttributes);
  mkdirSync(join(root, 'patches'));
  const patch = join(root, 'patches/gpui-pre-web-0.3.10-ime.patch');
  writeFileSync(patch, canonical);
  git('add', 'patches');
  rmSync(patch);
  git('checkout', '--', 'patches');
  assert.ok(readFileSync(patch).includes(Buffer.from('\r\n')));
  const corrupt = spawnSync('git', ['apply', '--numstat', patch], { cwd: root, encoding: 'utf8' });
  assert.notEqual(corrupt.status, 0);
  assert.match(corrupt.stderr, /corrupt patch/);

  writeFileSync(join(root, '.gitattributes'), attributes);
  git('add', '.gitattributes');
  rmSync(patch);
  git('checkout', '--', 'patches');
  assert.deepEqual(readFileSync(patch), canonical);
  assert.match(git('apply', '--numstat', patch).toString(), /src\/events\.rs/);
});

// Exact generated-file checks must survive a fresh Windows-style checkout,
// without relying on a later workflow step rewriting the working tree.
test('icon generation retains exact bytes with Windows checkout defaults', t => {
  const root = mkdtempSync(join(tmpdir(), 'pero-icon-checkout-'));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  const git = (...args) => execFileSync('git', args, { cwd: root, stdio: 'pipe' });
  const write = (path, contents) => {
    mkdirSync(dirname(join(root, path)), { recursive: true });
    writeFileSync(join(root, path), contents);
  };
  const generate = (...args) => spawnSync(process.execPath, ['scripts/generate-icons.mjs', ...args], {
    cwd: root, encoding: 'utf8',
  });
  const scripts = ['scripts/generate-icons.mjs', 'scripts/lib/content-icons.mjs'];
  for (const path of scripts) write(path, readFileSync(new URL(`../../${path}`, import.meta.url)));
  write('packages/icons/catalog.json', JSON.stringify({ 'layout-grid': {} }));
  write('packages/icons/content.json', JSON.stringify({
    kinds: { folder: 'layout-grid' }, languages: {}, filenames: {}, extensions: {}, apps: {},
  }));
  write('web/public/icons/layout-grid.svg', '<svg viewBox="0 0 24 24">\n<path d="M0 0"/>\n</svg>\n');
  const licenses = ['web/public/icons/LICENSE.txt', 'packages/icons/LICENSE-LUCIDE'];
  for (const path of licenses) write(path, readFileSync(new URL(`../../${path}`, import.meta.url), 'utf8').replaceAll('\r\n', '\n'));
  const outputs = [
    'crates/pero-chat-ui/src/assets.rs', 'packages/app-sdk/src/icons.generated.tsx',
    'packages/icons/content-data.generated.js', 'packages/icons/content-data.generated.d.ts',
    'crates/pero-contracts/src/content_icon_data.rs',
  ];
  for (const path of outputs) write(path, '');
  const initial = generate();
  assert.equal(initial.status, 0, initial.stderr);
  const canonical = outputs.map(path => readFileSync(join(root, path)));
  // A host's formatter preference must not change this generated byte contract.
  write('rustfmt.toml', 'newline_style = "Windows"\n');
  git('init', '-q');
  git('config', '--local', 'core.autocrlf', 'true');
  git('config', '--local', 'core.safecrlf', 'false');
  const emptyAttributes = join(root, 'empty-attributes');
  writeFileSync(emptyAttributes, '');
  git('config', '--local', 'core.attributesFile', emptyAttributes);
  git('add', '.');
  const checkout = () => {
    for (const path of [...outputs, ...licenses, ...scripts]) rmSync(join(root, path));
    git('checkout', '--', '.');
  };
  checkout();
  assert.ok(readFileSync(join(root, outputs[0])).includes(Buffer.from('\r\n')));
  const stale = generate('--check');
  assert.notEqual(stale.status, 0);
  assert.match(stale.stderr, /Regenerate icons:.*crates\/pero-chat-ui\/src\/assets.rs/);
  assert.match(stale.stderr, /"firstDifference":\d+,"actual":\{"length":\d+,"crlf":[1-9]/);

  write('.gitattributes', readFileSync(new URL('../../.gitattributes', import.meta.url)));
  git('add', '.gitattributes');
  checkout();
  const checked = generate('--check');
  assert.equal(checked.status, 0, checked.stderr);
  const regenerated = generate();
  assert.equal(regenerated.status, 0, regenerated.stderr);
  outputs.forEach((path, index) => assert.deepEqual(readFileSync(join(root, path)), canonical[index]));
  // --check still rejects both line-ending drift and actual stale content.
  for (const path of outputs) {
    const good = readFileSync(join(root, path), 'utf8');
    for (const bad of [good.replaceAll('\n', '\r\n'), `${good}// stale\n`]) {
      write(path, bad);
      const rejected = generate('--check');
      assert.notEqual(rejected.status, 0);
      assert.ok(rejected.stderr.includes(`(${path})`), rejected.stderr);
    }
    write(path, good);
  }
});
