// Generate only association data. Resolution and registration behavior live in the domain models.
export function contentIconData(catalog, associations) {
  const canonical = new Map();
  for (const [name, icon] of Object.entries(catalog)) {
    for (const alias of [name, ...(icon.aliases || [])]) {
      if (canonical.has(alias)) throw new Error(`Duplicate icon name: ${alias}`);
      canonical.set(alias,name);
    }
  }
  const sections = ['kinds','languages','filenames','extensions','apps'];
  if (Object.keys(associations).some(section=>!sections.includes(section))) throw new Error('Unknown content icon association section');
  for (const section of sections) {
    if (!associations[section] || typeof associations[section] !== 'object') throw new Error(`Missing icon section: ${section}`);
    for (const [key,icon] of Object.entries(associations[section])) {
      if (!key || key!==key.trim().toLowerCase() || canonical.get(icon)!==icon) throw new Error(`Invalid content icon association: ${section}/${key}`);
    }
  }
  const header='// Generated by scripts/generate-icons.mjs. Edit packages/icons/content.json and catalog.json.\n';
  return {
    javascript: `${header}export const associations = ${JSON.stringify(associations)};\nconst canonical = ${JSON.stringify(Object.fromEntries(canonical))};\nexport function canonicalIconName(name) {\n  return Object.hasOwn(canonical,name) ? canonical[name] : undefined;\n}\n`,
    declarations: `${header}export type BundledIconName = ${Object.keys(catalog).map(JSON.stringify).join(' | ')};\nexport declare const associations: ${JSON.stringify(associations)};\nexport declare function canonicalIconName(name:string):BundledIconName|undefined;\n`,
    rust: `${header}pub fn canonical(name:&str)->Option<&'static str> {\n    match name {\n${[...canonical].map(([alias,name])=>`        ${JSON.stringify(alias)} => Some(${JSON.stringify(name)}),`).join('\n')}\n        _=>None,\n    }\n}\npub fn lookup(section:&str,value:&str)->Option<&'static str> {\n    match (section,value) {\n${sections.flatMap(section=>Object.entries(associations[section]).map(([key,icon])=>`        (${JSON.stringify(section)},${JSON.stringify(key)})=>Some(${JSON.stringify(icon)}),`)).join('\n')}\n        _=>None,\n    }\n}\n`,
  };
}
